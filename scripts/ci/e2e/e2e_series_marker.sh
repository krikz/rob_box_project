#!/usr/bin/env bash
# Признак серии марафона для e2e-БД (issue #5077).
#
# Зачем. Узлы стирают e2e-БД только на переходе режима OFF->ON (#2890).
# Оборванный марафон (акт first, phase=first) включает режим, каст пишется в
# speakers.e2e.db, а потом раннер умирает. Режим снимает таймер владельца
# (e2e_release_after_s), но он снимает ТОЛЬКО флаг режима — файлы БД остаются.
# Следующий марафон стартует с first и падает на гарде refuse_first_mid_series:
# «в speakers.e2e.db уже N профил(ей)» (run 44973642247, 22.11).
#
# Просто удалять БД на снятии режима нельзя: каст держится между актами одной
# серии именно потому, что middle/last базы не трогают (#3972, #3904).
#
# Решение — признак серии, который видит харнесс, а не узел. Раннер и харнесс
# на разных машинах, поэтому раннер передаёт только id серии (в причине
# диспатча, отдельного input нет — потолок workflow_dispatch 25), а marker-файл
# пишет сам харнесс на машине прогона (по умолчанию /tmp/e2e_series.id).
# Удаляет харнесс, и только когда серия не активна: до гарда #5031 — для first
# без признаков продолжения и для одиночного прогона, и в leave_e2e_mode.
# Таймер владельца файлы не трогает — он внутри контейнера и маркера не видит;
# чистит следующий прогон, увидев чужой или протухший маркер.
#
# e2e_series_should_delete <marker-файл> <ttl-секунд> <current-id> [phase]  → одно слово:
#   delete — маркера нет, он пуст или битый; id в маркере не равен current-id
#            (чужая серия: её каст нам не принадлежит); current-id пуст
#            (одиночный прогон каст не держит); id совпал, но mtime старше TTL
#            (серия мертва); либо phase=first, а вторая строка маркера не
#            «opened» (серия с этим id ещё не прошла гард — её first оборвался
#            раньше, и каст в e2e-БД принадлежит тому обрыву, а не этому акту);
#   keep   — id в маркере равен current-id, маркер свежее TTL и (для first)
#            серия уже открыта: каст между актами этой серии на месте, не трогать.
#
# Сравнение id обязательно. TTL один не страхует повтор: инцидент 22.11 —
# оборванный прогон 23:50:59Z (run 44963710006), повтор 01:54:50Z, через 2 ч 04 мин,
# это меньше TTL 10800 с. Свежий маркер прошлой серии дал бы keep, и следующий
# first упал бы на гарде refuse_first_mid_series ровно так, как упал без этого
# признака (run 44973642247).
#
# TTL — запас на обрыв той же серии. Живая серия обновляет mtime маркера на
# каждом акте (e2e_series_marker_touch), поэтому посреди серии маркер не
# протухает. SIGKILL раннера маркер не трогает: его mtime застывает, и через TTL
# повтор той же серии видит мёртвую серию и удаляет. Прогон без серии
# (current-id пуст) каст не держит — для него delete при любом маркере.
#
# Второй строки маркера («opened») TTL не заменяет. Маркер пишет харнесс на
# машине прогона, а решение читается ДО гарда refuse_first_mid_series — раньше,
# чем акт вообще доходит до робота. Пока признаком был один id, повтор той же
# серии (раннер берёт E2E_SERIES_ID один раз на серию) через 2 ч 04 мин получал
# keep: id совпал, TTL не истёк, а маркер освежил прошлый прогон, умерший на
# гарде и до marathon_e2e_mode не дошедший. «opened» пишет только акт, прошедший
# гард, поэтому first без этой строки видит серию, которая ещё не открыта, и
# удаляет хвост оборванного прогона. middle/last вторую строку не читают: каст
# между актами держит #3972, и удаление до гарда для них запрещено.
e2e_series_should_delete() {
    local marker="${1:-}" ttl="${2:-}" current="${3:-}" phase="${4:-}"
    case "$ttl" in
        ""|*[!0-9]*) ttl=0 ;;
    esac
    # Маркера нет, он пуст или id в нём битый — не признак живой серии.
    local id=""
    if [ -n "$marker" ] && [ -f "$marker" ] && [ -s "$marker" ]; then
        id="$(head -1 "$marker" 2>/dev/null || true)"
    fi
    case "$id" in
        ""|*[!A-Za-z0-9_-]*) printf 'delete'; return 0 ;;
    esac
    # Чужой id — каст той серии нам не принадлежит. Пустой current — одиночный
    # прогон, он каст не держит. Оба случая — delete, TTL их не спасает.
    if [ -z "$current" ] || [ "$id" != "$current" ]; then
        printf 'delete'
        return 0
    fi
    local now mtime age
    now="$(date +%s)"
    mtime="$(date -r "$marker" +%s 2>/dev/null || stat -c %Y "$marker" 2>/dev/null || echo 0)"
    case "$mtime" in
        ""|*[!0-9]*) mtime=0 ;;
    esac
    age=$((now - mtime))
    if [ "$age" -ge "$ttl" ]; then
        printf 'delete'
        return 0
    fi
    # first требует, чтобы серия уже открылась. Вторую строку пишет
    # e2e_series_marker_opened, и только акт, прошедший гард. Нет строки или
    # она не «opened» — этот id ещё не дошёл до marathon_e2e_mode: каст в
    # e2e-БД принадлежит оборванному прогону, а не этому акту.
    if [ "$phase" = "first" ]; then
        local opened=""
        opened="$(sed -n '2p' "$marker" 2>/dev/null || true)"
        [ "$opened" = "opened" ] || { printf 'delete'; return 0; }
    fi
    printf 'keep'
}

# e2e_series_marker_touch <marker-файл> <series-id>  → rc 0, файл содержит id.
# Пишется только при непустом id: пустой id — прогон без серии, маркера нет,
# и снятие режима удалит БД (одиночный прогон не держит каст).
# Вторую строку НЕ трогает: «opened» ставит только акт, прошедший гард
# (e2e_series_marker_opened). Обновление mtime до гарда объявило бы живой
# серию, которая до гарда не дошла.
e2e_series_marker_touch() {
    local marker="${1:-}" id="${2:-}"
    [ -n "$id" ] || return 0
    case "$id" in
        *[!A-Za-z0-9_-]*)
            echo "E2E_FATAL: E2E_SERIES_ID='$id' — допустимы буквы, цифры, _ и - (#5077)" >&2
            return 2 ;;
    esac
    mkdir -p "$(dirname "$marker")" 2>/dev/null || true
    printf '%s\n' "$id" > "$marker"
}

# e2e_series_marker_opened <marker-файл> <series-id>  → rc 0, вторая строка «opened».
# Пишет только акт, прошедший гард refuse_first_mid_series и дошедший до
# marathon_e2e_mode. До этого момента first той же серии видит серию
# неоткрытой и удаляет хвост оборванного прогона, а не падает на гарде.
# Id сверяется со строкой, которую записал e2e_series_marker_touch: открыть
# чужую серию нельзя. Id пуст — прогон без серии, открывать нечего.
e2e_series_marker_opened() {
    local marker="${1:-}" id="${2:-}"
    [ -n "$id" ] || return 0
    local have=""
    have="$(head -1 "$marker" 2>/dev/null || true)"
    if [ "$have" != "$id" ]; then
        echo "E2E_FATAL: маркер серии ($marker) содержит '$have', а не '$id' (issue #5077)" >&2
        echo "           открыть чужую серию нельзя (issue #5077)" >&2
        return 2
    fi
    printf '%s\nopened\n' "$id" > "$marker"
}
