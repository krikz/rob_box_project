#!/usr/bin/env bash
# Признак серии марафона для e2e-БД (issue #5077).
#
# Зачем. Узлы стирают e2e-БД только на переходе режима OFF->ON (#2890).
# Оборванный марафон (акт first, phase=first) включает режим, каст пишется в
# speakers.e2e.db, а потом раннер умирает. Режим снимает таймер владельца
# (e2e_release_after_s), но он снимает ТОЛЬКО флаг режима — файлы БД остаются.
# Следующий марафон стартует с first и падает на гарде refuse_first_mid_series:
# «в speakers.e2e.db уже N профил(ей)» (run 44973642247, 22.11).
#
# Просто удалять БД на снятии режима нельзя: каст держится между актами одной
# серии именно потому, что middle/last базы не трогают (#3972, #3904).
#
# Решение — признак серии, который видит харнесс, а не узел. Раннер и харнесс
# на разных машинах, поэтому раннер передаёт только id серии (в причине
# диспатча, отдельного input нет — потолок workflow_dispatch 25), а marker-файл
# пишет сам харнесс на машине прогона (по умолчанию /tmp/e2e_series.id).
# Удаляет харнесс, и только когда серия не активна: до гарда #5031 — для first
# без признаков продолжения и для одиночного прогона, и в leave_e2e_mode.
# Таймер владельца файлы не трогает — он внутри контейнера и маркера не видит;
# чистит следующий прогон, увидев чужой или протухший маркер.
#
# e2e_series_should_delete <marker-файл> <ttl-секунд> <current-id>  → одно слово:
#   delete — маркера нет, он пуст или битый; id в маркере не равен current-id
#            (чужая серия: её каст нам не принадлежит); current-id пуст
#            (одиночный прогон каст не держит); либо id совпал, но mtime старше
#            TTL (серия мертва): e2e-БД можно удалить;
#   keep   — id в маркере равен current-id и маркер свежее TTL: каст между
#            актами этой серии на месте, не трогать.
#
# Сравнение id обязательно. TTL один не страхует повтор: инцидент 22.11 —
# оборванный прогон 23:50:59Z (run 44963710006), повтор 01:54:50Z, через 2 ч 04 мин,
# это меньше TTL 10800 с. Свежий маркер прошлой серии дал бы keep, и следующий
# first упал бы на гарде refuse_first_mid_series ровно так, как упал без этого
# признака (run 44973642247).
#
# TTL — запас на обрыв той же серии. Живая серия обновляет mtime маркера на
# каждом акте (e2e_series_marker_touch), поэтому посреди серии маркер не
# протухает. SIGKILL раннера маркер не трогает: его mtime застывает, и через TTL
# повтор той же серии видит мёртвую серию и удаляет. Прогон без серии
# (current-id пуст) каст не держит — для него delete при любом маркере.
e2e_series_should_delete() {
    local marker="${1:-}" ttl="${2:-}" current="${3:-}"
    case "$ttl" in
        ""|*[!0-9]*) ttl=0 ;;
    esac
    # Маркера нет, он пуст или id в нём битый — не признак живой серии.
    local id=""
    if [ -n "$marker" ] && [ -f "$marker" ] && [ -s "$marker" ]; then
        id="$(head -1 "$marker" 2>/dev/null || true)"
    fi
    case "$id" in
        ""|*[!A-Za-z0-9_-]*) printf 'delete'; return 0 ;;
    esac
    # Чужой id — каст той серии нам не принадлежит. Пустой current — одиночный
    # прогон, он каст не держит. Оба случая — delete, TTL их не спасает.
    if [ -z "$current" ] || [ "$id" != "$current" ]; then
        printf 'delete'
        return 0
    fi
    local now mtime age
    now="$(date +%s)"
    mtime="$(date -r "$marker" +%s 2>/dev/null || stat -c %Y "$marker" 2>/dev/null || echo 0)"
    case "$mtime" in
        ""|*[!0-9]*) mtime=0 ;;
    esac
    age=$((now - mtime))
    if [ "$age" -ge "$ttl" ]; then
        printf 'delete'
    else
        printf 'keep'
    fi
}

# e2e_series_marker_touch <marker-файл> <series-id>  → rc 0, файл содержит id.
# Пишется только при непустом id: пустой id — прогон без серии, маркера нет,
# и снятие режима удалит БД (одиночный прогон не держит каст).
e2e_series_marker_touch() {
    local marker="${1:-}" id="${2:-}"
    [ -n "$id" ] || return 0
    case "$id" in
        *[!A-Za-z0-9_-]*) echo "E2E_FATAL: E2E_SERIES_ID='$id' — допустимы только буквы, цифры, _ и - (issue #5077)" >&2; return 2 ;;
    esac
    mkdir -p "$(dirname "$marker")" 2>/dev/null || true
    printf '%s\n' "$id" > "$marker"
}
