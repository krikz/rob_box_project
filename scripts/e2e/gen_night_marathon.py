#: разрешённое восстановление ``wake_replay`` (:data:`WAKE_FRAGILE_RECOVER`); голос не меняется.
WAKE_FRAGILE_VOICES = frozenset({GRISHA})
_WAKE_START_RE = re.compile(r"^Робот\b", re.IGNORECASE)
_WAKE_END_RE = re.compile(r"\bробот\W*$", re.IGNORECASE)
_SENTENCE_END_RE = re.compile(r"[\s.!?…]+$")


def has_wake_start(text: str) -> bool:
    """Фраза начинается с вейка «Робот» (шаг с вейком -- ход; без него -- фон для бэклога)."""
    return bool(_WAKE_START_RE.match(text))


def wake_at_both_ends(text: str, voice: str) -> str:
    """Фраза голоса с хрупким вейком (:data:`WAKE_FRAGILE_VOICES`), начатая с «Робот», заканчивается «, робот» перед
    концевым знаком: «Робот, который час, я спрашиваю!» -> «Робот, который час, я спрашиваю, робот!». Другие голоса и
    фразы без вейка (фон для бэклога) -- как есть; повторный вызов фразу не меняет."""
    if voice not in WAKE_FRAGILE_VOICES or not has_wake_start(text) or _WAKE_END_RE.search(text):
        return text
    tail = _SENTENCE_END_RE.search(text)
    body = text[: tail.start()] if tail else text
    return f"{body}, робот{(tail.group(0).strip() if tail else '') or '.'}"


