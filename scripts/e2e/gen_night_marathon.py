# =============================================================================
# Сборка и запись файлов
# =============================================================================
def build() -> Dict[str, Dict[str, Any]]:
    """Все генерируемые файлы: ``{имя файла: payload}``. Без побочных эффектов (``--check`` сверяет с диском)."""
    files: Dict[str, Dict[str, Any]] = {}
    manifest: Dict[str, Any] = {
        "name": "night_voice_marathon_v1",
        "_comment": [
            "Порядок актов ЗНАЧИМ: акт N опирается на состояние, созданное",
            "актами < N (профили говорящих, факты в памяти, имена треков).",
            "Запускать строго по порядку одним раннером:",
            "  bash scripts/e2e/run_night_marathon.sh",
            "SSoT сюжета — scripts/e2e/gen_night_marathon.py; файлы актов",
            "генерируются, править их руками бессмысленно (перезатрутся).",
        ],
        "generated_by": "scripts/e2e/gen_night_marathon.py",
        "acts": [],
    }
    total = 0
    for a in ACTS:
        base = "night_marathon_act%d_%s" % (a["n"], a["slug"])
        scenario_name = base + "_v1.json"
        # ADR-0022 / resolve_acceptance_candidate() convention 4:
        #   <prefix>_acceptance_v1.json, где prefix = basename без _v<N>
        acceptance_name = base + "_acceptance_v1.json"
        scenario = {
            "name": base + "_v1",
            "stability": a["stability"],
            "act": a["n"],
            "title": a["title"],
            "description": a["description"],
            "generated_by": "scripts/e2e/gen_night_marathon.py",
            "cast": list(CAST.values()),
        }
        if a["n"] in ACTS_INHERITING_PREVIOUS:
            scenario["inherits_previous_act"] = True
            scenario["_inherits_previous_act_reason"] = INHERITS_REASON
        if a["recover"] is not None:
            scenario["recover"] = a["recover"]
        scenario["steps"] = a["steps"]
        acceptance = {
            "name": base + "_acceptance_v1",
            "schema_version": 1,
            "_comment": a["gate_comment"],
            "expected_tool_calls": a["gate_tools"],
            "must_not_call": [],
            # Каст #4038: команды людей синтезирует MiniMax (Yandex-роли склеиваются 0.84-0.92).
            "voice_provenance": {
                "voice": "anton",
                "tts": "minimax",
                "volume": 100,
                "llm": "minimax-m3",
            },
        }
        files[scenario_name] = scenario
        files[acceptance_name] = acceptance
        total += len(a["steps"])
        manifest["acts"].append(
            {
                "act": a["n"],
                "title": a["title"],
                "stability": a["stability"],
                "steps": len(a["steps"]),
                "scenario_file": ".github/e2e/scenarios/night/" + scenario_name,
                "acceptance_file": ".github/e2e/scenarios/night/" + acceptance_name,
            }
        )
        for m in MANUAL_ACTS:
            if m["after_act"] == a["n"]:
                manifest["acts"].append(_manual_entry(m))
                total += m["steps"]
    manifest["total_steps"] = total
    files["night_marathon_manifest.json"] = manifest
    return files


def _dump(payload: Dict[str, Any]) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def _read_manual_acts() -> Tuple[List[Dict[str, Any]], List[str]]:
    """Шаги рукописных актов 2b/2c с диска и имена файлов, которые прочитать не вышло. Шагов нет в SSoT, но реплики
    играет тот же харнесс в то же окно VAD; нечитаемый файл молча терял их из ``--check`` (его называет ``check()``)."""
    out: List[Dict[str, Any]] = []
    unreadable: List[str] = []
    for m in MANUAL_ACTS:
        name = "night_marathon_" + m["slug"] + "_v1.json"
        try:
            with open(os.path.join(OUT_DIR, name), encoding="utf-8") as fh:
                steps = json.load(fh)["steps"]
            out.extend(s for s in steps if isinstance(s, dict))
        except (OSError, ValueError, KeyError, TypeError):
            unreadable.append(name)
    return out, unreadable


def _manual_steps() -> List[Dict[str, Any]]:
    return _read_manual_acts()[0]


def phrases() -> Dict[str, Tuple[str, str]]:
    """``label -> (voice, text)`` всех реплик марафона: генерируемые акты и рукописные 2b/2c."""
    steps = [s for a in ACTS for s in a["steps"]] + _manual_steps()
    return {s["label"]: (s["voice"], s["text"]) for s in steps if s.get("text") and s.get("voice")}


def phrase_report() -> Tuple[List[pb.Verdict], List[pb.Verdict]]:
    """Вердикты по длине всех реплик: ``(красные, тугие)``. Красная -- не влезет в окно VAD (замер выше потолка либо
    оценка без замера выше порога); тугая -- замер с запасом меньше секунды (``⚠️ запас < 1s`` харнесса)."""
    verdicts = [pb.verdict(label, voice, text, PHRASE_STORE) for label, (voice, text) in phrases().items()]
    return [v for v in verdicts if v.level == pb.TOO_LONG], [v for v in verdicts if v.level == pb.TIGHT]


def _stale_files() -> List[str]:
    """Файлы, которые генератор собрал бы иначе, чем они лежат на диске (нет файла -- тоже устарел)."""
    stale: List[str] = []
    for name, payload in build().items():
        try:
            with open(os.path.join(OUT_DIR, name), encoding="utf-8", newline="") as fh:
                on_disk = fh.read().replace("\r\n", "\n")
        except OSError:
            on_disk = None
        if on_disk != _dump(payload):
            stale.append(name)
    return stale


def check() -> int:
    """``--check``: JSON на диске == то, что соберёт генератор, рукописные акты 2b/2c читаются и каждая реплика влезает
    в окно VAD робота (``phrase_budget``, #4077 П2). 0 -- всё в порядке, 1 -- расходятся файлы, акт не читается или
    есть слишком длинная реплика."""
    stale = _stale_files()
    unreadable = _read_manual_acts()[1]
    red, tight = phrase_report()
    for v in tight:
        print("  ⚠️ тугая реплика (запас < %g с): %s" % (pb.VAD_BUDGET_S - pb.EQ_TIGHT_S, v.describe()))
    if stale:
        print("JSON устарели относительно gen_night_marathon.py "
              "(перегенерируйте: py -3 scripts/e2e/gen_night_marathon.py):")
        for name in stale:
            print("  - " + name)
    if unreadable:
        print("Рукописные акты не читаются (их реплик --check не видит):")
        for name in unreadable:
            print("  - " + name)
    if red:
        print("Реплики не влезают в окно VAD робота (бюджет %g с; замер выше %g с либо оценка без замера выше %g с):"
              % (pb.VAD_BUDGET_S, pb.EQ_ERROR_S, pb.EQ_TIGHT_S))
        for v in red:
            print("  - " + v.describe() + " (до %d симв без замера)" % pb.char_limit(v.voice))
    if stale or red or unreadable:
        return 1
    print("JSON актуальны (%d файлов), реплик в окне VAD: %d" % (len(build()), len(phrases())))
    return 0


def learn(log_paths: List[str]) -> int:
    """``--learn <лог акта>...``: замеры длительности реплик из логов прогона -> ``phrase_eq_measured.json``.
    Берутся только шаги, у которых текст и голос в логе равны текущим (правленые пропускаются)."""
    store: Dict[str, Dict[str, object]] = dict(PHRASE_STORE)
    skipped: List[str] = []
    for path in log_paths:
        with open(path, encoding="utf-8", errors="replace") as fh:
            log = fh.read()
        found = re.search(r"_(\d+)\.log$", os.path.basename(path))
        store, gone = pb.merge_measures(store, pb.parse_run_log(log), phrases(), found.group(1) if found else "")
        skipped += gone
    with open(PHRASE_STORE_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(pb.dump_store(store))
    PHRASE_STORE.clear()
    PHRASE_STORE.update(store)
    print("замеров в словаре: %d (%s)" % (len(store), PHRASE_STORE_PATH))
    if skipped:
        print("пропущены (текст или голос в логе не равны текущим): " + ", ".join(sorted(set(skipped))))
    return 0


def emit() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    files = build()
    for name, payload in files.items():
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(_dump(payload))
    total = 0
    for a in ACTS:
        total += len(a["steps"])
        print("act %-2d %-22s %2d steps  %s" % (a["n"], a["slug"], len(a["steps"]), a["stability"]))
    total += sum(m["steps"] for m in MANUAL_ACTS)
    print("-" * 52)
    print("acts: %d (+%d рукописных)   total steps: %d" % (len(ACTS), len(MANUAL_ACTS), total))
    print("out:  %s" % OUT_DIR)


def _utf8_console() -> None:
    """Консоль Windows-хоста -- cp1252 (``PYTHONUTF8`` не задан): ``print()`` кириллицы и эмодзи падал
    ``UnicodeEncodeError``, а раннер марафона звал ``--check`` и принимал падение за красный сценарий. Вывод CLI
    всегда UTF-8, как у питон-блока раннера и у ``test_e2e_scenario_playable.sh``."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass


if __name__ == "__main__":
    _utf8_console()
    if "--check" in sys.argv[1:]:
        raise SystemExit(check())
    if "--learn" in sys.argv[1:]:
        raise SystemExit(learn(sys.argv[sys.argv.index("--learn") + 1:]))
    emit()
