# --- хрупкий вейк у голоса с акцентом (решение Шифу 28.10, n210) -------------------------------------------------
#: Голоса, у которых STT путает вейк «Робот» («ребят», «привет»: n210 краснел в каждом марафоне, 28.10 распознано
#: «ребят я не маша…»). Решение Шифу 28.10: «пусть Гриша при отвале повторит робот ну и добавь в его фразу … робот в
