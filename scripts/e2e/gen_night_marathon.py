def _guard_phrase_length(label: str, voice: str, text: str) -> None:
    """Реплика, которая не влезет в окно VAD робота, -- ошибка сборки, а не ``FAIL scenario_too_long`` посреди акта
    (#4077 П2: n302 13.78 с, n702 12.89 с, 27.10). Решает :mod:`phrase_budget`: замер из словаря (текст и голос те же)
    либо оценка по символам; тугой замер (запас < 1 с) не ошибка -- о нём говорит ``--check``."""
    found = pb.verdict(label, voice, text, PHRASE_STORE)
    if found.level == pb.TOO_LONG:
        raise ValueError(
            f"{found.describe()}: окно VAD робота даёт {pb.VAD_BUDGET_S:g} с (потолок "
            f"{pb.EQ_ERROR_S:g} с по замеру, {pb.EQ_TIGHT_S:g} с по оценке); без замера реплику голоса {voice} держи "
            f"до {pb.char_limit(voice)} символов или разбей на два шага (замер -- ``--learn``)")


def step(
    label: str,
    text: str,
    voice: str = SASHA,
    patterns: Optional[List[str]] = None,
    expect_tools: Optional[List[str]] = None,
    must_not: Optional[List[str]] = None,
    must_not_say: Optional[List[str]] = None,
    must_not_identify_as: Optional[List[str]] = None,
    keywords: Optional[List[str]] = None,
    voice_changed: bool = False,
    expect: str = "",
    retry: int = 0,
    why: str = "",
    discovery_tools: Optional[List[str]] = None,
    barge_in: Optional[Dict[str, Any]] = None,
    silent_ok: bool = False,
    skip_when: str = "",
    sleep_before_sec: int = 0,
    stt_keys: Optional[List[str]] = None,
) -> Dict[str, Any]:
    # Хрупкий вейк (решение Шифу 28.10, n210): вейк и в начале, и в конце фразы -- ДО проверки длины, она судит итог.
    text = wake_at_both_ends(text, voice)
    _guard_phrase_length(label, voice, text)
    s: Dict[str, Any] = {"label": label, "voice": voice, "text": text}
    # Пауза ПЕРЕД шагом (харнесс: ``sleep_before_sec``, раньше проверки ``skip_when``): напр. песня пишется ~90-150 с.
    if sleep_before_sec:
        s["sleep_before_sec"] = sleep_before_sec
    # Issue #3857 -- barge_in: НАМЕРЕННОЕ перебивание. Без него харнесс перед шагом ждёт тишины, и
    # «стой/хватит посреди речи» на деле говорилось в тишину. С ним: ждём якорь в речи предыдущей
    # фразы, играем поверх через delay_sec. Якорь не наступил -> SKIP barge_in_anchor_missing.
    if barge_in:
        s["barge_in"] = barge_in
    # Issue #3863/#3880 -- silent_ok: ход без речи допустим (Tier-1 «стоп»/«хватит»: llm_calls=0, речи нет, речь
    # робота гасится). Харнесс (e2e_voice_lib.sh) читает поле ``silent_ok``; конец хода -- ``📊 [turn] stage=done``.
    # Само по себе поле молчание не проверяет -- смысл шагу даёт паттерн отмены речи.
    if silent_ok:
        s["silent_ok"] = True
    s["patterns"] = patterns or []
    # #3971 R4: после старта выступления повтор фразы заказывает второе -- ретрай у такого шага запрещён структурой.
    if retry and any(p.startswith(PERFORM_STARTED_MARK) for p in s["patterns"]):
        raise ValueError(f"{label}: шаг ждёт выступление ({PERFORM_STARTED_MARK}…) -- retry запрещён (#3971 R4)")
    acc = _acceptance(
        expect_tools, discovery_tools, must_not, must_not_say, must_not_identify_as, keywords, voice_changed, why
    )
    if acc:
        s["acceptance"] = acc
    if expect:
        s["expect"] = expect
    if retry:
        s["retry_acceptance"] = retry
    # Промах вейка у хрупкого голоса: после «Робот!» шаг повторяет свою фразу один раз (e2e_events.WAKE_REPLAY).
    recover: Optional[List[str]] = list(WAKE_FRAGILE_RECOVER) if voice in WAKE_FRAGILE_VOICES and has_wake_start(text) else None
    # #4196: ключевые слова фразы, которые STT не должен терять (n411 «говори» -> «гарри»): нет слова в ПРИНЯТО -- фраза ещё раз.
    if stt_keys:
        s[eev.STT_KEYS_FIELD] = list(stt_keys)
        recover = [*(recover if recover is not None else eev.RECOVERABLE), eev.STT_REPLAY]
        recover = list(dict.fromkeys(recover))
    if recover is not None:
        s["recover"] = recover
        eev.recover_kinds({}, s)  # схема поля -- до записи файла, а не FATAL посреди прогона
        eev.stt_keys(s)
    if why and "acceptance" not in s:
        s["_why"] = why
    # R21 разбора 26.10: предусловие внешнего мира (ключ SKIP_WHEN): нарушено -- харнесс шаг не играет, SKIP <ключ>.
    if skip_when:
        s["skip_when"] = _skip_field(skip_when)
    return s


def _skip_field(reason: str) -> Dict[str, Any]:
    """Поле ``skip_when`` шага по ключу :data:`SKIP_WHEN` (читает ``e2e_events.skip_rule``); ``absent`` -- только при
    правиле «строки нет»."""
    rule = SKIP_WHEN[reason]
    return {"reason": reason, "log": rule.log, **({"absent": True} if rule.absent else {}),
            **({"deck": rule.deck} if rule.deck else {})}


def _acceptance(
    expect_tools: Optional[List[str]],
    discovery_tools: Optional[List[str]],
    must_not: Optional[List[str]],
    must_not_say: Optional[List[str]],
    must_not_identify_as: Optional[List[str]],
    keywords: Optional[List[str]],
    voice_changed: bool,
    why: str,
) -> Dict[str, Any]:
    """Блок ``acceptance`` шага (пустой -- шаг без него). Порядок ключей -- как в JSON актов (сверяет ``--check``).

    Issue #2406 -- ``discovery_tools``: тул, который ОБЯЗАН быть вызван ДО первого голосового ответа (проверяется
    check_acceptance через first_invocation_position/first_voice_cycle_position).
    Issue #2779 -- ``must_not_say`` НЕ то же самое, что ``must_not``: ``must_not`` (-> ``must_not_call``) свободным
    текстом матчит ВЕСЬ лог шага, включая строки биометрии (``Speaker: 'Борис'``), там имя диктора тавтологически
    КРАСНО. ``must_not_say`` ищет ТОЛЬКО в речи робота (``robot_speech()``, тот же канал, что ``expected_keywords``).
    """
    fields = (
        ("expected_tool_calls", expect_tools),
        ("discovery_tools", discovery_tools),
        # #3971: заглушка кода -- не ответ и не результат ни для какого шага (n707 27.10): ход, закрытый заглушкой
        # (``status=done`` вместо ``finished``), и фраза-заглушка в речи краснят шаг всегда.
        ("must_not_call", [*(must_not or []), TURN_FALLBACK]),
        ("must_not_say", [*(must_not_say or []), STUB_SPEECH]),
        ("must_not_identify_as", must_not_identify_as),
        ("expected_keywords", keywords),
        ("voice_changed", True if voice_changed else None),
    )
    acc: Dict[str, Any] = {key: value for key, value in fields if value}
    if not acc:
        return acc
    acc.setdefault("expected_tool_calls", [])
    acc.setdefault("must_not_call", [])
    if why:
        acc["_comment"] = why
    return acc


def action_step(
    label: str,
    text: str,
    result_of: Optional[List[str]] = None,
    *,
    result: str = "",
    known_red: str = "",
    patterns: Optional[List[str]] = None,
    must_not: Optional[List[str]] = None,
    **kwargs: Any,
) -> Dict[str, Any]:
    """Шаг-действие: PASS только при МАРКЕРЕ РЕЗУЛЬТАТА в логе робота (#3971), а не по речи или имени тула.

    ``result_of`` -- тулы, любой из которых обязан закончиться ``✅ Инструмент <tool> выполнен успешно``;
    ``result`` -- вид результата, который просила реплика (ключ :data:`RESULT_KINDS`): его доказательства идут в
    ``patterns``, подмены -- в ``must_not_call``, противоречащая речь -- в ``must_not_say``, сверка с музыкой до шага --
    в поле ``music_compare``. Всегда: ход дошёл до ``stage=done status=finished`` и в шаге нет ``stage=timeout``.
    ``known_red`` -- причина, по которой шаг сегодня красный по делу (поле ``_known_red`` для людей; харнесс его
    не читает, шаг остаётся красным честно).
    """
    kind = RESULT_KINDS[result]
    pats = list(patterns or [])
    if result_of:
        pats.append(tool_done(*result_of))
    pats.extend(kind.proof)
    pats.append(TURN_DONE)
    if kind.contradicted_by:
        kwargs["must_not_say"] = list(kwargs.get("must_not_say") or []) + [kind.contradicted_by]
    forbidden = list(must_not or []) + list(kind.substitute) + [TURN_TIMEOUT]
    s = step(label, text, patterns=pats, must_not=forbidden, **kwargs)
    if kind.compare:
        s[eev.COMPARE_FIELD] = kind.compare
    s["_result_markers"] = {"tools": list(result_of or []), "result": result}
    if known_red:
        s["_known_red"] = known_red
    return s


