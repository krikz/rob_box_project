"""Бюджет healthcheck nav2 (#5150).

Числа — из замеров, не из головы. Менять можно только вместе с новым замером
и комментарием здесь: гейт compose и деплоя читают эти же константы.

Замеры Main Pi 10.1.1.10, 23.11.2026 (стенд под нагрузкой, load average 10–22):

* ``ros2 lifecycle get`` одного узла: 3.5–7.7 с (3512/4260/4340/4744/5390/6218/
  6980/7720 мс). Три таких вызова подряд — 10.5–16.8 с (замер скрипта целиком
  16.76 с, замер Шифу 16.025 с). Docker Timeout был 10 с, поэтому живые
  active-узлы красились unhealthy (exit=-1, «Health check exceeded timeout»).
* Измерено, не догадано: два процесса ``ros2 lifecycle get`` одновременно жгут
  ядра — 100 % и 72.7 % CPU, контейнер nav2 139 % при load average 12–14 на
  4 ядрах (замер Шифу 23.11). Три таких вызова подряд не укладываются в
  docker Timeout 10 с.
* Совпадение по времени, не доказанный механизм: пока шли эти пробы,
  lifecycle_manager писал «CRITICAL FAILURE: SERVER controller_server IS DOWN
  after not receiving a heartbeat for 4000 ms» и гасил managed-узлы на 47–79 с
  (диагностика /tmp/nav2_tfdrop_1123, 23.11). Дефолт nav2 ``bond_timeout`` —
  4.0 с, в ``nav2_params.yaml`` не переопределён. Длительность CLI сама по себе
  не доказывает, что запрос занял executor сервера: это гипотеза (новый
  zenoh-сеанс на каждый CLI плюс голод CPU), не факт.
* Один процесс ``rclpy`` на три сервиса ``/get_state``: discovery и три ответа
  за 1523 мс (замер 07:28:51Z, узлы active). Одна сессия zenoh вместо трёх.

Отсюда бюджет. Решение Шифу 23.11: docker Timeout на роботе НЕ поднимать.
Проба обязана уложиться в текущие 10 с. Общий дедлайн трёх запросов короче
bond (3.0 < 4.0) — ориентир, не доказательство механизма. Интервал остаётся
15 с и больше дедлайна, поэтому проверки не накладываются.
"""

from __future__ import annotations

# Дефолт nav2 bond_timeout, с. В nav2_params.yaml не задан — берётся 4.0 с.
# Ориентир дедлайна пробы. Что CLI длиннее этого окна занимает executor
# сервера — гипотеза, не доказанный факт (см. шапку модуля).
BOND_TIMEOUT_S = 4.0

# Общий дедлайн трёх запросов в одном процессе. 3.0 < 4.0 (ориентир bond) и
# 3.0 < docker Timeout 10 с, который решением Шифу 23.11 не поднимаем.
# 1523 мс замера одного процесса укладывается с двукратным запасом; дольше
# 3 с — честный красный «не ответили», а не ложный зелёный.
PROBE_DEADLINE_S = 3.0

# Docker Timeout. Решением Шифу 23.11 на роботе НЕ поднимается: прежние 10 с
# остались, потому что три CLI (10.5–16.8 с) в них не влезали, а одна проба
# (1.5 с замера + дедлайн 3 с) влезает с запасом. Поднимать Timeout значило бы
# дольше держать проверку, которая и так грузит хост.
DOCKER_TIMEOUT_S = 10

# Interval > дедлайн пробы: следующая проверка не стартует, пока предыдущая
# жива. 15 с — текущее значение compose, не меняется (Timeout не поднимаем).
DOCKER_INTERVAL_S = 15

# Start_period не трогаем смыслом #5043: зависание configure наблюдали 176 с,
# 60 с кончалось раньше. 90 с остаётся.
DOCKER_START_PERIOD_S = 90

DOCKER_RETRIES = 3

# Гейт L: Deploy and Verify делает два замера Health.Status с паузой 15 с
# (CONFIRM_INTERVAL в workflow, не меняется). Пауза равна Interval: за это
# окно проходит ровно одна проба, и гейт не ждёт дольше, чем docker сам.
# Поднимать паузу до «StartPeriod + retries × Timeout + Interval» имело смысл
# только вместе с подъёмом Timeout — решение Шифу 23.11 это запретило.
DEPLOY_CONFIRM_INTERVAL_S = DOCKER_INTERVAL_S


def budget_holds() -> bool:
    """Инварианты бюджета. Ложь — числа в модуле противоречат друг другу."""
    return (
        0 < PROBE_DEADLINE_S < BOND_TIMEOUT_S
        and PROBE_DEADLINE_S < DOCKER_TIMEOUT_S
        and DOCKER_TIMEOUT_S == 10
        and PROBE_DEADLINE_S < DOCKER_INTERVAL_S
        and DOCKER_START_PERIOD_S >= 90
        and DEPLOY_CONFIRM_INTERVAL_S == DOCKER_INTERVAL_S
    )
