"""club_stereo.py — стерео-раскладка club-трека (issue #3310, эпик #3312).

До правки весь выход был моно: корреляция L/R записи робота 1.00 против 0.04
у живого диджея (58 мин, эталон Шифу). Выход — ReSpeaker, 2 канала (FL/FR),
колонок две, панорама слышна.

Раскладка по партиям:

========  ==========================================================
партия    ``pan``
========  ==========================================================
d1 kick   нет (центр): низ моно-совместим, бочка не «гуляет»
p2 bass   нет (центр): то же
p1 lead   нет (центр): ведущий голос на оси
d2 hats   пинг-понг ±:data:`PAN_HATS`: стороны чередуются на каждом ударе
d3        то же, но начиная с другой стороны: клэп или слой сэмплов DJ_Dave
p3 pad    медленный треугольник ±:data:`PAN_PAD_WIDTH` на 8 тактов
========  ==========================================================

Почему пинг-понг по ударам, а не «хэты вправо, клэп влево». Громкость
слоёв разная (хэты 0.14, клэп 0.24): статичная сторона дала бы перекос L/R
в сумме. Список ``pan`` индексируется номером шага (как ``amplify`` в club:
пропуски тоже шаги), поэтому список строится ПО РИСУНКУ партии: сторона
меняется на каждом ударе (:func:`pan_steps`). Схема «+,-,+,-» по номеру шага
не годится — оффбит-хэты бьют на 2/6/10/14 и ушли бы в одну сторону, а
шаффл (6 ударов из 10 на одной чётности) перекосился бы при Туэ–Морсе.
Список на два такта (32 значения), чтобы и при нечётном числе ударов в такте
за два такта было поровну. d3 стартует с противоположной стороны.

Пэд — единственный ``linvar`` на ``pan``: вся ширина в одном голосе,
плавно (треугольник, не скачок) и симметрично, за цикл из 8 тактов
среднее равно нулю. Санитайзер ``var``/``linvar`` на ``pan`` не трогает
(капает только ``amp``/``amplify``).

Что не проверено на роботе: ``pan`` — стандартный аргумент синтов renardo
(``Pan2.ar(osc, pan)``, см. ``renardo_synthdef_patches``), но слышно ли
панораму через ReSpeaker и не уезжает ли моно-буфер ``loop`` (PlayBuf.ar(2))
в один канал — не замерено. Приёмка — ``compare.py`` на записи после деплоя.
"""

from __future__ import annotations

import re
from typing import List

from rob_box_music import knowledge as kn

#: Таблицы панорамы — в ``rob_box_music.knowledge`` (ADR-0149 §8.1, PR-3c; механика — PR-9):
#: вынос хэтов/клэпа от центра (0.4: заметно, но не «в одну колонку»), полуширина пэда (шире хэтов:
#: пэд — длинные ноты, там ширина слышнее всего), период качания пэда в долях (8 тактов = 4 аккорда по 2 такта).
PAN_HATS = kn.PAN_HATS
PAN_PAD_WIDTH = kn.PAN_PAD_WIDTH
PAD_PAN_BEATS = kn.PAD_PAN_BEATS


def _fmt(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def pan_steps(pattern: str, width: float, first: int = 1) -> List[float]:
    """32 значения ``pan`` (два такта 16-х): сторона меняется на КАЖДОМ ударе ``pattern``.

    Пропуск (``.``) стороны не занимает — на звук не влияет. Группа
    ``(-.)`` считается ударом. Счёт идёт сквозь оба такта. ``first`` —
    сторона первого удара (+1 вправо, -1 влево).
    """
    side, out = -first, []  # флип происходит ДО записи удара
    for _ in range(2):
        for tok in re.findall(r"\([^)]*\)|.", pattern):
            if tok != ".":
                side = -side
            out.append(side * width)
    return out


def pan_list(pattern: str, width: float, first: int = 1) -> str:
    """Аргумент ``pan=[...]`` (32 шага) для плеера с ``dur=1/4`` и строкой ``pattern``."""
    return "[" + ", ".join(_fmt(v) for v in pan_steps(pattern, width, first)) + "]"


def pan_alternating(width: float, mirror: bool = False) -> str:
    """Аргумент ``pan=[-w, w]`` для слоя, где одно событие — доля или луп целиком."""
    a, b = (width, -width) if mirror else (-width, width)
    return f"[{_fmt(a)}, {_fmt(b)}]"


def pad_pan() -> str:
    """Аргумент ``pan=linvar(...)`` пэда: -w → +w → -w за :data:`PAD_PAN_BEATS` долей."""
    half = PAD_PAN_BEATS // 2
    w = _fmt(PAN_PAD_WIDTH)
    return f"linvar([-{w}, {w}, -{w}], [{half}, {half}, 0])"
