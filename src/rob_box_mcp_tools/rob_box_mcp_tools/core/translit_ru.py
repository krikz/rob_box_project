"""Транслитерация кириллицы в латиницу для поиска по англоязычному архиву RTTTL.

Архив мелодий латинский, а имена русских народных песен в нём — это
транслитерация (``kalinkav`` «Kalinka V1.0», ``polka``). Русский запрос
«Калинка»/«Полька» без перевода в латиницу распадался на ноль токенов
(issue #3264). Схема — простая, без словаря под конкретные песни: мягкий и
твёрдый знаки опускаются, остальные буквы — по привычной латинской записи.
"""

from __future__ import annotations

import re
from typing import Dict

_MAP: Dict[str, str] = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

_CYRILLIC_RUN_RE = re.compile(r"[а-яё]+")

#: Хвост-версия записи архива («Kalinka V1.0», «… v2»): в разговорном
#: запросе её нет, а если юзер её произнёс — она не должна ломать поиск.
_VERSION_TAIL_RE = re.compile(r"[\s_]+v\d+(?:\.\d+)*$", re.IGNORECASE)


def transliterate_ru(text: str) -> str:
    """Заменить кириллические слова в уже приведённом к нижнему регистру *text*."""
    return _CYRILLIC_RUN_RE.sub(lambda m: "".join(_MAP[ch] for ch in m.group(0)), text)


def strip_version_tail(text: str) -> str:
    """Срезать хвост версии («v1.0») — общий для запроса и для title записи."""
    return _VERSION_TAIL_RE.sub("", text)
