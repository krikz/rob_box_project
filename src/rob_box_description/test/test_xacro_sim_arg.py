"""Аргумент ``sim`` в rob_box.xacro: робот не меняется, сим получает своё.

План docs/research/2026-11-04-gazebo-sim-navigation.md §6 шаг 1.

* ``sim:=false`` (и без аргумента) — URDF для robot_state_publisher и
  ros2-control на роботе. Он обязан совпадать с эталоном
  ``golden/rob_box_real.urdf`` — выводом xacro с develop ДО появления
  аргумента (a2f8a5ffe). Любая правка боевого URDF теперь видна в diff
  эталона и делается осознанно: перегенерировать эталон тем же xacro.
* ``sim:=true`` — железо Gazebo, цилиндры колёс, лидар 360°, IMU, масса ~20 кг.

Нужен ROS 2 ``xacro`` в PATH (ros-humble-xacro); без него тест пропускается.
"""

from __future__ import annotations

import shutil
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

PKG = Path(__file__).resolve().parents[1]
XACRO_FILE = PKG / "urdf" / "rob_box.xacro"
GOLDEN = PKG / "test" / "golden" / "rob_box_real.urdf"

pytestmark = pytest.mark.skipif(
    shutil.which("xacro") is None, reason="нет ROS 2 xacro в PATH"
)


def _xacro(*args: str) -> str:
    out = subprocess.run(
        ["xacro", str(XACRO_FILE), *args],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return _strip_banner(out)


def _strip_banner(text: str) -> str:
    """Убрать шапку «autogenerated by xacro from <путь>» — в ней абсолютный путь."""
    lines = text.splitlines()
    return "\n".join(
        line
        for line in lines
        if "autogenerated by xacro" not in line
        and "EDITING THIS FILE BY HAND" not in line
        and not line.startswith("<!-- ====")
    )


def test_real_robot_urdf_is_unchanged_without_arg():
    assert _xacro() == _strip_banner(GOLDEN.read_text(encoding="utf-8"))


def test_real_robot_urdf_is_unchanged_with_sim_false():
    assert _xacro("sim:=false") == _strip_banner(GOLDEN.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def sim_urdf() -> ET.Element:
    return ET.fromstring(_xacro("sim:=true", "controllers_yaml:=/tmp/cm.yaml"))


def test_sim_uses_gazebo_hardware_not_vesc(sim_urdf):
    plugins = [p.text for p in sim_urdf.iter("plugin") if p.text]
    assert "gz_ros2_control/GazeboSimSystem" in plugins
    assert not any("vesc" in p.lower() for p in plugins)
    gz_plugin = sim_urdf.find("./gazebo/plugin[@filename='gz_ros2_control-system']")
    assert gz_plugin is not None
    assert gz_plugin.findtext("parameters") == "/tmp/cm.yaml"


def test_sim_keeps_same_wheel_joints_as_robot(sim_urdf):
    real = ET.fromstring(_xacro())
    assert _ros2_control_joints(sim_urdf) == _ros2_control_joints(real)


def _ros2_control_joints(root: ET.Element) -> list[str]:
    return sorted(j.get("name") for j in root.find("ros2_control").iter("joint"))


def test_sim_wheels_collide_as_cylinders(sim_urdf):
    for link in sim_urdf.iter("link"):
        if link.get("name", "").endswith("_wheel"):
            assert link.find("./collision/geometry/cylinder") is not None, link.get("name")


def test_sim_lidar_is_full_circle_from_015m(sim_urdf):
    sensor = sim_urdf.find(".//sensor[@type='gpu_lidar']")
    assert sensor is not None
    assert sensor.findtext("ray/scan/horizontal/samples") == "360"
    lo = float(sensor.findtext("ray/scan/horizontal/min_angle"))
    hi = float(sensor.findtext("ray/scan/horizontal/max_angle"))
    assert hi - lo == pytest.approx(2 * 3.14159265 * 359 / 360, abs=1e-4)
    assert float(sensor.findtext("ray/range/min")) == pytest.approx(0.15)
    assert sensor.findtext("ignition_frame_id") == "lslidar_n10"


def test_sim_has_imu_on_camera_imu_frame(sim_urdf):
    ref = [g for g in sim_urdf.findall("gazebo") if g.find("sensor[@type='imu']") is not None]
    assert [g.get("reference") for g in ref] == ["camera_imu_frame"]


def test_sim_mass_is_about_20kg(sim_urdf):
    total = sum(float(m.get("value")) for m in sim_urdf.iter("mass"))
    assert 19.0 < total < 21.5, total


def test_sim_default_has_no_robot_param_node(sim_urdf):
    """Обычный сим: плагин берёт URDF у /robot_state_publisher по умолчанию."""
    gz_plugin = sim_urdf.find("./gazebo/plugin[@filename='gz_ros2_control-system']")
    assert gz_plugin.find("robot_param_node") is None


def test_hil_points_gz_ros2_control_at_sim_rsp():
    """HIL (#4371): URDF для gz_ros2_control — у сим-RSP, а не у RSP Main Pi."""
    urdf = ET.fromstring(_xacro("sim:=true", "sim_robot_param_node:=/sim/robot_state_publisher"))
    gz_plugin = urdf.find("./gazebo/plugin[@filename='gz_ros2_control-system']")
    assert gz_plugin.findtext("robot_param_node") == "/sim/robot_state_publisher"


def test_real_robot_urdf_ignores_hil_arg():
    golden = _strip_banner(GOLDEN.read_text(encoding="utf-8"))
    assert _xacro("sim_robot_param_node:=/sim/robot_state_publisher") == golden
