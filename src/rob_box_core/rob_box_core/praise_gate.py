"""praise_gate.py — «модель не судит своё творение сама» (ADR-0132 PR-7).

``save_arrangement_preset`` (rob_box_mcp_tools) сохраняет ручки только что
сыгранного трека под именем мелодии. Решение владельца репо (ADR-0132 §7):
модель не может решить сама, что аранжировка получилась настолько хорошо,
что её стоит запомнить как дефолт для всех будущих проигрываний этой
мелодии — это МАСШТАБИРУЕТ одно субъективное суждение модели на весь
архив. Гейт — по ПОСЛЕДНЕЙ реплике юзера: явная похвала («кайф», «супер»,
«сохрани») или явная просьба запомнить/сохранить. Отказ модели не
разрешён обходить формулировкой «мне кажется, юзеру понравилось».

Чистая функция (без ROS, без rclpy) — так её может использовать и
``rob_box_harness`` (где живёт последняя реплика юзера в ходе диалога,
:mod:`rob_box_harness.core.agent_core`), и ``rob_box_mcp_tools`` (сам
тул), не тяня зависимости друг на друга — общий дом обеих сторон здесь,
в ``rob_box_core``.
"""

from __future__ import annotations

import re

__all__ = ["PRAISE_WORDS", "SAVE_REQUEST_WORDS", "contains_praise"]

#: Явная похвала/восторг по треку — русские разговорные маркеры (issue
#: ADR-0132 §7, живые логи 23.09.2026: «кайф», «огонь, сохрани» и т.п.).
#: Однокоренные формы ловятся через основы (``supers?``), не полный список
#: словоформ — регэксп ниже матчит по границе слова с суффиксом.
PRAISE_WORDS: frozenset[str] = frozenset({
    "кайф", "кайфово", "огонь", "круто", "крутo", "класс", "классно",
    "супер", "отлично", "отпад", "шикарно", "шикарн", "бомба", "бомбически",
    "здорово", "нравится", "понравилось", "восторг", "великолепно",
    "потрясающе", "идеально", "топ", "зачёт", "зачет", "красота", "wow",
    "awesome", "love it", "nice one",
})

#: Явная просьба запомнить/сохранить именно этот вариант.
SAVE_REQUEST_WORDS: frozenset[str] = frozenset({
    "сохрани", "сохраните", "запомни", "запомните", "запиши этот вариант",
    "оставь этот вариант", "save this", "remember this",
})

_ALL_WORDS = PRAISE_WORDS | SAVE_REQUEST_WORDS
#: Самые длинные фразы — первыми, чтобы более специфичная не потерялась
#: за короткой подстрокой при построении альтернативы regex.
_PATTERN = re.compile(
    r"(?<!\w)(" + "|".join(re.escape(w) for w in sorted(_ALL_WORDS, key=len, reverse=True)) + r")",
    re.IGNORECASE,
)

#: Слова, у которых явное отрицание прямо перед ними меняет смысл на
#: противоположный («не нравится» — это НЕ похвала). Остальной словарь
#: (императивы «сохрани», междометия «кайф») отрицанием почти не
#: встречается в реальной речи и намеренно не проверяется — общее правило
#: гейта: пропуск похвалы дороже одного лишнего совпадения.
_NEGATABLE = frozenset({"нравится", "понравилось"})
_NEGATION_BEFORE_RE = re.compile(r"\bне\s+$", re.IGNORECASE)


def contains_praise(text: str) -> bool:
    """``True`` — *text* (последняя реплика юзера) содержит явную похвалу
    или явную просьбу сохранить именно эту аранжировку.

    Подстрочный поиск по границе слова слева (справа — нет: ловит формы
    «супер», «супергероя», «классный», «сохрани/сохраните» и т.п. —
    ложные срабатывания на однокоренных, но НЕ похвальных словах на
    практике не встречались). Исключение — :data:`_NEGATABLE`: «не
    нравится» не должно отпирать сохранение только потому, что подстрока
    «нравится» совпала.
    """
    if not text or not text.strip():
        return False
    for match in _PATTERN.finditer(text):
        word = match.group(1).lower()
        if word in _NEGATABLE and _NEGATION_BEFORE_RE.search(text[: match.start()]):
            continue
        return True
    return False
