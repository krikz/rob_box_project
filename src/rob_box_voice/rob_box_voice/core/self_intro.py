"""Самопредставление в реплике -- детерминированный сигнал (issue #2925).

Зачем
=====
Регистрация диктора и вопрос о личности решались только LLM и
биометрией. Что человек САМ сказал о себе в этой реплике, не учитывалось
никем, кроме LLM, -- и на роботе это разошлось тремя способами (issue
#2925, run 35931295672 / 35933157262):

1. «привет я борис …» незнакомым голосом -- LLM поздоровалась «Здравствуй,
   Борис!», но ``register_speaker`` не вызвала (класс #2406);
2. тот же голос похож на Сашу (``single``) -- робот сам спросил «Саша,
   это ты?», хотя человек в этой же реплике назвался Борисом;
3. «запомни про меня: Дарья болит за Спартак» (ослышка STT, голос
   уверенно Борис) -- LLM вызвала ``register_speaker('Дарья')``, и в базе
   появился третий человек.

Модуль отвечает на один вопрос: «назвал ли человек себя в ЭТОЙ реплике, и
каким именем». Без ROS2 -- тестируется напрямую.

Границы (что считаем представлением)
====================================
* **Явные обороты** -- «меня зовут X», «зовут меня X», «моё имя X», «имя
  мне X», «запомни меня как X»: X -- любое слово, прошедшее фильтр
  служебных слов. Вопрос «как меня зовут?» представлением не считается.
* **Короткое «я X» / «это я, X»** -- только если X есть в словаре
  распространённых имён (:data:`KNOWN_FIRST_NAMES`, именительный падеж).
  «я заглянул», «я думаю», «я Борису сказал» -- не имя. Редкое имя в
  форме «я X» не распознаётся -- это остаётся на LLM, как было до #2925
  (честная граница: словарь даёт точность, а не полноту).
* **Не представление:** «это X» (так знакомят ТРЕТЬЕГО: «знакомься, это
  Борис»), голое имя без оборота, «запомни про меня: X …» (так диктуют
  факт), «я не X …» (поправка -- её ведёт LLM через ``old_name``/rename,
  #1101; авто-регистрация тут завела бы второй профиль рядом с
  переименованным).
"""

from __future__ import annotations

import re
from typing import Optional

# Служебные слова, которые после «меня зовут» бывают вместо имени (#1101:
# «робот меня зовут Денис говорю» → LLM передала «зовут»), плюс частые
# слова-паразиты STT. Сравнение -- в нижнем регистре, ё → е.
