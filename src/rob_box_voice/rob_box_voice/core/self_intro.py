_WORD = r"([а-яёa-z][а-яёa-z\-]*)"
# «меня зовут X» и родственные явные обороты: имя -- любое слово.
_EXPLICIT_RE = re.compile(
    r"(?:(?<![а-яё])(как\s+)?меня\s+зовут|зовут\s+меня|мо[её]\s+имя|"
    r"имя\s+мне|запомни\s+меня\s+как)\s*[:,\-—]?\s*" + _WORD,
    re.IGNORECASE,
)
# «я X», «я — X», «это я, X»: имя -- только из словаря.
_SHORT_RE = re.compile(
    r"(?<![а-яё])(?:это\s+)?я\s*[,\-—]?\s+(?:это\s+)?" + _WORD,
    re.IGNORECASE,
)
# «я не X» -- поправка имени (#1101), не представление.
_CORRECTION_RE = re.compile(
    r"(?<![а-яё])я\s+не\s+" + _WORD, re.IGNORECASE
)


def _norm(word: str) -> str:
    return word.strip(".,!?;:-— ").lower().replace("ё", "е")


def _display(word: str) -> str:
    cleaned = word.strip(".,!?;:-— ")
    return cleaned[:1].upper() + cleaned[1:].lower()


def _is_correction(text: str) -> bool:
    return any(
        _norm(m.group(1)) in KNOWN_FIRST_NAMES
        for m in _CORRECTION_RE.finditer(text)
    )


def _explicit_name(text: str) -> Optional[str]:
    for match in _EXPLICIT_RE.finditer(text):
        if match.group(1):  # «как меня зовут …» -- вопрос, не ответ
            continue
        word = _norm(match.group(2))
        if len(word) >= 2 and word not in _NOT_A_NAME:
            return _display(match.group(2))
    return None


def _short_name(text: str) -> Optional[str]:
    for match in _SHORT_RE.finditer(text):
        if _norm(match.group(1)) in KNOWN_FIRST_NAMES:
            return _display(match.group(1))
    return None


def extract_self_intro_name(text: Optional[str]) -> Optional[str]:
    """Имя, которым человек назвал СЕБЯ в реплике ``text``, или ``None``.

    Границы -- в docstring модуля. Возвращает имя с заглавной буквы
    («борис» → «Борис»).
    """
    if not text or _is_correction(text):
        return None
    return _explicit_name(text) or _short_name(text)


def same_person_name(left: Optional[str], right: Optional[str]) -> bool:
    """Одно ли это имя (регистр, пробелы, ё/е не важны). Пустое -- нет."""
    a = _norm(left or "")
    b = _norm(right or "")
    return bool(a) and a == b


