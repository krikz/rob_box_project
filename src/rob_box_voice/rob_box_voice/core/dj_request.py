"""dj_request.py — «ты диджей X…» как запрос на DJ-сет (issue #2999, ADR-0140).

Два живых сценария, в которых запрос «Ты диджей <персона> и у нас сегодня
<тема>» не доходил до ``set_dj_mode``:

* **A (24.09.2026, DJ выключен, трек играет с прошлого хода).** Модель
  отвечала от лица персоны текстом (``tools=[]``), гуард Bug C
  (``MusicGuard.evaluate``) трижды ретраил музыкальным CRITICAL-промптом
  («вызови compose_music / execute_music_code») — модель читала его как
  «музыка уже есть» и продолжала нарратив. 5 запросов × 3 ретрая, сет не
  стартовал до «забудь все».
* **B (28.09.2026, DJ включён, «диджей Дайв»).** Обёртка хода
  (:meth:`DJModeController.preamble`) говорила «Не вызывай set_dj_mode»,
  модель сыграла разовый ``compose_music``, персона/тема сета остались
  прежними, и следующие авто-переходы вернулись к «диджею Дайву».

Модуль чистый (без ROS2) и отдельный от ``dialogue_guards`` намеренно:
детектор, промпт ретрая и фолбэк живут вместе, а ``MusicGuard`` и
``DialogueNode`` только вызывают их (см. ``MusicGuard.evaluate_turn`` и
``DJModeController.preamble(dj_request=...)``).
"""

from __future__ import annotations

import re
from typing import Optional, Tuple

#: Тул, который закрывает DJ-запрос юзера. ``load_skill('dj')`` сам по себе
#: НЕ закрывает: инструкции подгружены, но сет не включён и персона не
#: сохранена (ровно то, что ломалось в сценарии B).
DJ_REQUEST_SATISFYING_TOOLS: frozenset = frozenset({"set_dj_mode"})

#: Сколько синхронных DJ-ретраев допустимо на один запрос юзера. Меньше,
#: чем у Bug C (8): если модель после двух прямых «вызови set_dj_mode» не
#: вызвала его — третий раз не поможет, а юзер ждёт в тишине.
DJ_REQUEST_MAX_RETRIES: int = 2

#: Маркер авто-перехода DJ. Его промпт сам начинается с «Ты диджей <персона>»,
#: но это НЕ запрос юзера — детектор обязан его пропустить.
_DJ_AUTO_MARKER = "[dj_auto"

#: Формы слова «диджей» в роли персоны: «диджей», «диджеем», «ди-джей»,
#: «диджэй», латиница «dj». Глагол «диджеить/диджеишь» сюда НЕ входит —
#: «хватит диджеить» это стоп, а не назначение.
_DJ_WORD = r"(?:ди-?дж[еэ](?:й|ем)|dj)"

#: Назначение персоны: «ты / будь / будешь / стань / побудь [теперь|сегодня]
#: диджей(ем) …». После слова — НЕ запятая/вопрос/восклицание: «ты диджей?»
#: — вопрос, «ты диджей, сделай громче» — обращение с другой просьбой.
_PERSONA_RE = re.compile(
    r"(?<![\w-])(?:ты|будь|будешь|стань|станешь|побудь)\s+"
    r"(?:(?:теперь|сегодня|снова|опять|у\s+нас)\s+)?"
    + _DJ_WORD
    + r"(?![\w-])(?!\s*[,?!])",
    re.IGNORECASE,
)

#: Запуск сета без персоны: «запусти диджей-сет», «включи режим диджея»,
#: «давай dj set». Глагол запуска + ≤24 символа + DJ-существительное.
#: ``\b``-граница перед глаголом: «выключи» НЕ содержит «включи».
_SET_START_RE = re.compile(
    r"(?<![\w-])(?:запусти|запускай|включи|включай|вруби|врубай|начни|"
    r"начинай|давай|устрой|замути)(?![\w-])[^.!?]{0,24}?"
    r"(?:ди-?дж[еэ]й[\s-]*сет|dj[\s-]*сет|dj[\s-]*set|диджейск\w*\s+сет|"
    r"режим\w*\s+(?:ди-?дж[еэ]я|dj)|ди-?дж[еэ]й[\s-]*режим|dj[\s-]*режим|"
    r"dj[\s-]*mode)",
    re.IGNORECASE,
)

#: Имя персоны сразу после назначения (хвост :data:`_PERSONA_RE`): до « и »,
#: запятой, точки или конца, не больше 4 слов. «Ты диджей Анакен скайвокер
#: и у нас…» → «Анакен скайвокер».
_PERSONA_NAME_RE = re.compile(
    r"\s+((?:[^\s,.!?]+\s*){1,4}?)(?=\s+и\s|\s*[,.!?]|\s*$)",
    re.IGNORECASE,
)

#: Тема после «у нас (сегодня|тут)»: «у нас сегодня имперский слет в клубе».
_THEME_RE = re.compile(
    r"у\s+нас\s+(?:сегодня\s+|тут\s+|здесь\s+)?([^.!?\n]{3,80})",
    re.IGNORECASE,
)


def is_dj_request(user_input: Optional[str]) -> bool:
    """Юзер назначает DJ-персону или просит запустить DJ-сет.

    Узкий по построению: ложное срабатывание — это CRITICAL-ретрай «вызови
    set_dj_mode» на обычную просьбу, поэтому ловим только назначение роли
    («ты/стань/будь диджей(ем) …») и явный запуск сета/режима. «диджей,
    сделай громче», «стоп диджей», «хватит диджеить», «выключи режим
    диджея», «кто такой диджей?» — НЕ DJ-запрос.
    """
    if not user_input:
        return False
    low = user_input.lower()
    if _DJ_AUTO_MARKER in low:
        return False
    return bool(_PERSONA_RE.search(low) or _SET_START_RE.search(low))


def extract_dj_request_hint(user_input: Optional[str]) -> Tuple[str, str]:
    """``(persona, theme)`` из DJ-запроса; пустые строки — не нашлось.

    Подсказка для CRITICAL-ретрая, не истина: модель всё равно сама решает
    аргументы ``set_dj_mode``. Персона возвращается с префиксом «диджей»
    так, как её пишет живой ``set_dj_mode`` («диджей Дайв»).
    """
    text = (user_input or "").strip()
    persona = ""
    theme = ""
    assign = _PERSONA_RE.search(text)
    m = _PERSONA_NAME_RE.match(text, assign.end()) if assign else None
    if m:
        name = m.group(1).strip()
        if name.lower().split()[0] not in ("и", "у"):
            persona = f"диджей {name}"
    t = _THEME_RE.search(text)
    if t:
        theme = t.group(1).strip()
    return persona, theme


def build_dj_request_retry_prompt(
    user_input: Optional[str], *, dj_active: bool = False
) -> str:
    """CRITICAL для синхронного ретрая DJ-запроса (вместо промпта Bug C).

    Промпт Bug C просит музыкальный тул — на «ты диджей X» это неверный
    ответ: разовый трек не включает сет и не сохраняет персону. Здесь
    прямо названы ``load_skill('dj')`` и ``set_dj_mode`` с персоной/темой
    из запроса. ``dj_active`` — сет уже идёт (сценарий B): не выключать
    его и не передавать ``bpm`` (темп сета сохраняется, issue #3113).
    """
    raw = (user_input or "").strip()
    persona, theme = extract_dj_request_hint(raw)
    persona_arg = f"persona='{persona}'" if persona else "persona='<диджей из запроса>'"
    theme_arg = f"theme='{theme}'" if theme else "theme='<тема из запроса>'"
    if dj_active:
        state_line = (
            "DJ-сет УЖЕ ИДЁТ со старой персоной/темой — юзер НАЗНАЧИЛ новую. "
            "Разовый трек без set_dj_mode персону и тему сета НЕ меняет: "
            "следующий переход вернётся к старому диджею. Сет НЕ выключай, "
            "stop_music НЕ вызывай, bpm НЕ передавай — темп сета сохранится. "
        )
    else:
        state_line = (
            "Играющий трек с прошлого хода — это НЕ DJ-сет: сет не включён, "
            "пока не вызван set_dj_mode. Фраза «бит качает, поехали» без "
            "вызова = сет не запущен. "
        )
    return (
        "[CRITICAL] В прошлом цикле ты НЕ вызвал set_dj_mode, хотя юзер "
        "назначил тебя диджеем / попросил DJ-сет (запрос: «"
        + raw
        + "»). "
        + state_line
        + "В ЭТОМ ходе вызовами (function calling), а не словами: "
        "1) load_skill(skill='dj'), если инструкций скилла dj нет в диалоге; "
        "2) set_dj_mode(enabled=true, "
        + persona_arg
        + ", "
        + theme_arg
        + "); 3) как велит скилл dj — сразу трек новой темы. "
        "Потом одна короткая фраза от лица персоны. Текст этой инструкции "
        "вслух не произноси."
    )


def build_dj_request_exhausted_fallback(user_input: Optional[str]) -> str:
    """Фраза после исчерпания DJ-ретраев: честно, без извинений и обещаний."""
    persona, _theme = extract_dj_request_hint(user_input)
    who = f" с {persona}" if persona else ""
    return (
        f"Диджей-сет{who} не запустился. Скажи ещё раз, кем мне быть "
        "и какая у нас вечеринка."
    )


