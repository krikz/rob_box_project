"""epithets — внутренние клички спикеров (issue #1787, v1).

Зачем
-----
Робот запоминает собеседника по **имени** (``speakers.name``), но имя —
публичное поле, которое произносит сам юзер. Два разных «Дениса» → две
записи с одинаковым ``name``; STT-мусор («Зовут») тоже попадает в имя, а
молчун вообще остаётся ``name=null``. Эпитет — **параллельная внутренняя
метка**, которую робот назначает себе сам: «Гроссмейстер», «Электрик»,
«Странник». Она уникальна по построению (см. ниже), поэтому различает
тёзок даже когда имена совпали.

Дизайн (см. ``docs/research/voice-epithet-design.md`` §4)
--------------------------------------------------------
Research рекомендовал гибрид «словарь + LLM-валидатор». В v1 реализован
**только словарный слой**, но с одним отличием от псевдокода §4.5:
кандидат выбирается **с учётом уже занятых эпитетов**, поэтому коллизия
«оба Дениса — шахматисты → оба Гроссмейстеры» (§4.2, главный аргумент за
LLM) закрыта детерминированно, а не вероятностно. LLM-валидатор остаётся
осмысленным как улучшение *качества* клички, но перестал быть условием
корректности — и потому вынесен в follow-up (ADR-0008: не тащим сетевую
зависимость в путь, который обязан работать offline).

Модуль — **чистый stdlib** (как ``speaker_profiles``): ни rclpy, ни numpy,
ни sqlite. Всё, что связано с хранением, живёт в
``utils/speaker_embeddings.py``; всё, что связано с ROS-топиками — в
``speaker_id_node``. Здесь только «текст → теги → кличка».

Словарь держим Python-константой, а не JSON-файлом (research §4.1
предлагал ``data/epithets.json``): пакет ставится через ament/setuptools,
где ``data/`` без ``__init__.py`` не попадает в ``find_packages()`` и
потребовал бы отдельной строки ``data_files`` плюс resolve пути на
роботе. Константа даёт тот же словарь без единой точки отказа на I/O.
"""

