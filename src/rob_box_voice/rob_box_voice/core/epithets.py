# кличку «Гость»: фильтр «незнакомца» (#2864) закрывал только LLM-слой.
# «Гость», «Прохожий», «Визитёр», «Пришелец» заменены на месте (чтобы
# сдвиг _rotation у остальных кличек не поехал); тест требует, чтобы ни
# одна словарная кличка не проходила is_stranger_epithet.
DEFAULT_POOL_NEUTRAL: Tuple[str, ...] = (
    "Странник", "Приятель", "Новичок", "Тихий", "Рассказчик", "Спутник",
    "Сосед", "Наблюдатель", "Собеседник", "Созерцатель", "Попутчик",
)
DEFAULT_POOL_RESTLESS: Tuple[str, ...] = (
    "Вихрь", "Беспокойный", "Порыв", "Штормовой", "Искра", "Нерв",
    "Сполох", "Мятежник", "Гроза", "Стремительный", "Тревожный",
)

# Порог, ниже которого sentiment считается «тревожным».
RESTLESS_SENTIMENT: float = -0.25

_POSITIVE_WORDS: Tuple[str, ...] = (
    "спасиб", "отличн", "круто", "класс", "супер", "рад", "нравит",
    "хорош", "прекрасн", "люблю", "молодец", "весел",
)
_NEGATIVE_WORDS: Tuple[str, ...] = (
    "плохо", "ужас", "бесит", "ненавиж", "устал", "надоел", "злюсь",
    "боюсь", "страшн", "проблем", "тревож", "грустн", "больно",
)


# ── Датаклассы ───────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class TagScore:
    """Тема речи и её доля в выборке."""

    cluster: str
    hits: int
    share: float  # 0.0–1.0, доля от всех попаданий по всем кластерам


@dataclass(frozen=True)
class EpithetCandidate:
    """Кандидат-кличка с происхождением."""

    label: str
    source_cluster: str  # «шахматы», «техно» или «default»
    confidence: float    # доля кластера (для default — 0.5)


# ── Текст → теги ─────────────────────────────────────────────────────────────


def _normalize(text: Optional[str]) -> List[str]:
    """Разбить текст на нормализованные слова (только lower).

    ``ё`` намеренно НЕ схлопывается в ``е``: словарь содержит оба варианта
    там, где это важно («костер»/«костёр»), и слепая замена сделала бы
    сравнение неявным для читателя словаря.
    """
    if not text:
        return []
    return [w.lower() for w in _WORD_RE.findall(text)]


def extract_tags(messages: Sequence[str], *, top_n: int = 3) -> List[TagScore]:
    """Посчитать темы в репликах спикера.

    Каждое слово сравнивается с префиксами кластеров; одно слово попадает
    максимум в один кластер (первый совпавший — словарь упорядочен,
    поведение детерминировано). Возвращает топ-``top_n`` кластеров по
    числу попаданий, по убыванию.

    Пустой результат — если реплик слишком мало (``MIN_WORDS_FOR_TAGS``)
    или ни одно слово не попало в словарь: тогда вызывающий код обязан
    работать по дефолтному пулу, а не додумывать тему.
    """
    words: List[str] = []
    for msg in messages or ():
        words.extend(_normalize(msg))
    if len(words) < MIN_WORDS_FOR_TAGS:
        return []

    counts: Dict[str, int] = {}
    for word in words:
        for cluster, prefixes in CLUSTER_KEYWORDS.items():
            if any(word.startswith(p) for p in prefixes):
                counts[cluster] = counts.get(cluster, 0) + 1
                break
    if not counts:
        return []

    total = sum(counts.values())
    ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))
    return [
        TagScore(cluster=c, hits=n, share=n / total)
        for c, n in ranked[: max(0, top_n)]
    ]


def score_sentiment(messages: Sequence[str]) -> float:
    """Грубая валентность речи в диапазоне [-1.0, 1.0].

    Не «эмоция голоса» (для этого нужен VAD/prosody — research §4.1 ось 2,
    отложена), а лексический счёт по словарю. Используется только для
    выбора дефолтного пула кличек и как метаданные профиля.
    """
    words: List[str] = []
    for msg in messages or ():
        words.extend(_normalize(msg))
    if not words:
        return 0.0
    pos = sum(1 for w in words if any(w.startswith(p) for p in _POSITIVE_WORDS))
    neg = sum(1 for w in words if any(w.startswith(p) for p in _NEGATIVE_WORDS))
    if pos + neg == 0:
        return 0.0
    return (pos - neg) / (pos + neg)


# ── Выбор эпитета ────────────────────────────────────────────────────────────


def _rotation(speaker_id: str, size: int) -> int:
    """Стабильный сдвиг по списку кандидатов для данного speaker_id.

    ``hash()`` не годится — он солится PYTHONHASHSEED и меняется от
    запуска к запуску, а эпитет обязан быть воспроизводимым (иначе тест
    зелёный «через раз», а робот после рестарта предлагает другую кличку
    тому же голосу). ``crc32`` детерминирован.
    """
    if size <= 0:
        return 0
    return zlib.crc32((speaker_id or "").encode("utf-8")) % size


def _pick_free(
    pool: Sequence[str], speaker_id: str, taken: Iterable[str]
) -> Optional[str]:
    """Первый свободный кандидат из ``pool``, начиная со сдвига speaker_id.

    Именно здесь закрывается коллизия «двух Денисов-шахматистов»: сдвиг
    разводит их по разным местам списка, а проверка ``taken`` гарантирует,
    что второй не получит кличку первого даже при совпадении сдвига.
    """
    taken_lower = {str(t).strip().lower() for t in taken if t}
    size = len(pool)
    if size == 0:
        return None
    start = _rotation(speaker_id, size)
    for i in range(size):
        candidate = pool[(start + i) % size]
        if candidate.lower() not in taken_lower:
            return candidate
    return None


def choose_epithet(
    tags: Sequence[TagScore],
    *,
    speaker_id: str,
    taken: Iterable[str] = (),
    sentiment: float = 0.0,
) -> EpithetCandidate:
    """Выбрать уникальную кличку по темам речи.

    Порядок попыток:
      1. кластеры из ``tags`` (по убыванию доли) — первый свободный
         эпитет кластера;
      2. дефолтный пул (нейтральный или «беспокойный» по ``sentiment``);
      3. если занято вообще всё — нумерованный суффикс к кандидату
         («Странник-2»). Уникальность важнее красоты: две одинаковые
         клички снова сделали бы эпитет бесполезным.

    Функция **всегда** возвращает кандидата — вызывающий код не обязан
    обрабатывать ``None`` (research §5.1: юзер получает кличку сразу).
    """
    taken_list = [t for t in taken if t]
    for tag in tags or ():
        pool = EPITHET_LEXICON.get(tag.cluster)
        if not pool:
            continue
        label = _pick_free(pool, speaker_id, taken_list)
        if label:
            return EpithetCandidate(label, tag.cluster, round(tag.share, 3))

    default_pool = (
        DEFAULT_POOL_RESTLESS
        if sentiment <= RESTLESS_SENTIMENT
        else DEFAULT_POOL_NEUTRAL
    )
    label = _pick_free(default_pool, speaker_id, taken_list)
    if label:
        return EpithetCandidate(label, "default", 0.5)

    # Всё занято — добавляем счётчик. Возможно только на очень большой
    # базе спикеров (>200 профилей).
    base = default_pool[_rotation(speaker_id, len(default_pool))]
    taken_lower = {str(t).strip().lower() for t in taken_list}
    suffix = 2
    while f"{base}-{suffix}".lower() in taken_lower:
        suffix += 1
    return EpithetCandidate(f"{base}-{suffix}", "default", 0.3)


# ── Слой 2: кличка от LLM ────────────────────────────────────────────────────


def build_llm_prompt(
    messages: Sequence[str],
    *,
    fallback: str,
    cluster: str = "default",
    hints: Sequence[str] = (),
) -> str:
    """Собрать запрос к LLM на выдумывание клички.

    Issue #2887 (решение Шифу 23.09.2026): просим 2–4 слова из черт
    человека — того, что он рассказал о себе, — а не общую метку.
    Словарный кандидат (``fallback``) и соседи по кластеру (``hints``)
    идут в промпт как **слова-ориентиры по теме**, не как образец формы:
    они однословные, а нужна кличка из нескольких слов.

    Issue #2926 — живой прогон показал, что при пустой истории реплик
    модель дословно повторяла плейсхолдер «(пока нечего показать)» как
    саму кличку. Плейсхолдер переписан так, чтобы не выглядеть ответом
    («реплик нет»), а промпт явно разрешает вернуть ``-``, когда фактов о
    человеке не хватает: словарная кличка (``fallback``) уже записана в БД
    и не нуждается в замене выдумкой без опоры на реальные черты.
    """
    recent = "\n".join(f"- {m}" for m in list(messages)[-5:] if m)
    hint_line = ", ".join(hints[:3]) if hints else fallback
    return (
        "Ты придумываешь ВНУТРЕННЮЮ кличку собеседника для робота. "
        "Она нужна, чтобы различать людей с одинаковыми именами, и "
        "НИКОГДА не произносится вслух.\n\n"
        f"Основная тема собеседника: {cluster}.\n"
        f"Последние реплики:\n{recent or '(реплик нет)'}\n\n"
        f"Слова-ориентиры по теме (можно взять за основу): {hint_line}.\n\n"
        f"Верни кличку из {LLM_EPITHET_MIN_WORDS}–{LLM_EPITHET_MAX_WORDS} слов "
        "на русском, первое слово с большой буквы, например «Мудрый "
        "собеседник-спортсмен» или «Ночной паяльщик моторов». Собери её из "
        "того, что человек рассказал о себе: занятия, увлечения, манера "
        "речи — чтобы она подходила именно ему, а не любому. Без кавычек, "
        "пояснений, цифр и знаков препинания (дефис внутри слова можно). "
        "Не используй имя человека. Кличка должна быть уважительной: без "
        "насмешек над внешностью, здоровьем, национальностью и без грубых "
        "слов. Это человек, которого робот уже знает, — не называй его "
        "незнакомцем, гостем, анонимом или чужаком. Если фактов о человеке "
        "не хватает — не выдумывай ничего похожего на кличку и не пиши, что "
        "нечего сказать: просто верни один символ «-», кличка тогда "
        "останется прежней."
    )


def normalize_epithet(label: Optional[str]) -> str:
    """Ключ сравнения кличек: нижний регистр, ё→е, одиночные пробелы.

    Issue #2887 — занятость сверяется по всей кличке целиком; без
    нормализации «Мудрый  Собеседник» и «мудрый собеседник» считались бы
    разными метками.
    """
    return " ".join(str(label or "").lower().replace("ё", "е").split())


def _extract_llm_label(raw: str) -> List[str]:
    """Вырезать из ответа LLM слова клички (без подписи и пояснений)."""
    text = str(raw).strip()
    # «Кличка: Кулибин» — модель любит подписать ответ. Двоеточие делит
    # подпись и саму кличку; без этого в БД уехала бы «Кличка».
    if ":" in text:
        text = text.rsplit(":", 1)[-1]
    # «Мудрый собеседник — любит бег» / «…, потому что…» — пояснение
    # отрезаем по первому разделителю.
    text = _EXPLANATION_SPLIT_RE.split(text.strip().strip("\"'«»`"), 1)[0]
    words = [w.strip("\"'«»`") for w in text.split()]
    return [w for w in words if w]


def _label_format_problem(words: Sequence[str]) -> Optional[str]:
    """Причина отказа по форме клички (число слов, символы) или ``None``."""
    if not (LLM_EPITHET_MIN_WORDS <= len(words) <= LLM_EPITHET_MAX_WORDS):
        return REJECT_WORD_COUNT
    label = " ".join(words)
    if not (LLM_EPITHET_MIN_LEN <= len(label) <= LLM_EPITHET_MAX_LEN):
        return REJECT_INVALID
    if not _LLM_EPITHET_FIRST_RE.match(words[0]):
        return REJECT_INVALID
    if not all(_LLM_EPITHET_WORD_RE.match(w) for w in words[1:]):
        return REJECT_INVALID
    if any(w.lower() in _NON_EPITHET_WORDS for w in words):
        return REJECT_INVALID
    return None


def _has_person_name(label: str, names: Iterable[str]) -> bool:
    """В кличке есть имя знакомого человека (своё или чужое).

    Кличка с именем читается LLM как упоминание этого человека:
    «Борис-путешественник» у Саши — ровно та путаница, от которой кличка
    защищает. Имена от 4 букв сверяются по основе без последней буквы
    («Борис» ловит «Борисыч»), короче — только целиком.
    """
    parts = re.split(r"[\s-]+", normalize_epithet(label))
    for name in names:
        key = normalize_epithet(name)
        if not key or " " in key:
            continue
        stem = key[:-1] if len(key) >= 4 else key
        if any(p == key or (len(key) >= 4 and p.startswith(stem)) for p in parts):
            return True
    return False


def check_llm_epithet(
    raw: Optional[str],
    *,
    taken: Iterable[str] = (),
    names: Iterable[str] = (),
) -> Tuple[Optional[str], Optional[str]]:
    """Проверить кличку, придуманную LLM: ``(кличка, None)`` или ``(None, причина)``.

    Причины отказа (issue #2886 — раньше в логе было только «отклонена»,
    и нельзя было понять, сработал фильтр или уникальность):

    * ``REJECT_EMPTY`` — пустой ответ;
    * ``REJECT_STRANGER`` — смысл «неизвестный человек» (issue #2864);
      проверяется до числа слов, чтобы однословный «Незнакомец» в логе
      был виден как незнакомец, а не как «одно слово»;
    * ``REJECT_REFUSAL`` — ответ на деле отказ/служебная реплика модели
      («Пока нечего показать», «Недостаточно данных») (issue #2926);
      проверяется до числа слов по той же причине, что и ``REJECT_STRANGER``
      — «Пока нечего показать» само по себе укладывается в 2–4 слова и без
      этой проверки прошло бы дальше;
    * ``REJECT_WORD_COUNT`` — не 2–4 слова (issue #2887). Лишнее не
      обрезаем: обрывок фразы хуже словарной клички, которая уже в БД;
    * ``REJECT_INVALID`` — длина вне границ, цифры/эмодзи, маленькая
      буква у первого слова, слова отказа («Не могу придумать»);
    * ``REJECT_NAME`` — в кличке имя знакомого человека (``names``);
    * ``REJECT_TAKEN`` — кличка уже у другого профиля; сравнение всей
      клички целиком через ``normalize_epithet``.

    Отказ означает «оставить словарного кандидата» — именно поэтому
    словарный слой пишется в БД ДО запроса к LLM: у робота всегда есть
    рабочая метка, даже если сеть легла или модель вернула мусор
    (ADR-0008 — деградация без тишины).
    """
    words = _extract_llm_label(raw) if raw else []
    if not words:
        return None, REJECT_EMPTY
    label = " ".join(words)
    if is_stranger_epithet(label):
        return None, REJECT_STRANGER
    if is_refusal_epithet(label):
        return None, REJECT_REFUSAL
    problem = _label_format_problem(words)
    if problem:
        return None, problem
    if _has_person_name(label, names):
        return None, REJECT_NAME
    if normalize_epithet(label) in {normalize_epithet(t) for t in taken if t}:
        return None, REJECT_TAKEN
    return label, None


def sanitize_llm_epithet(
    raw: Optional[str], *, taken: Iterable[str] = (), names: Iterable[str] = ()
) -> Optional[str]:
    """Кличка от LLM или ``None``, если не годится (причина — ``check_llm_epithet``)."""
    return check_llm_epithet(raw, taken=taken, names=names)[0]


def is_stranger_epithet(label: Optional[str]) -> bool:
    """Кличка по смыслу означает «неизвестный человек» (issue #2864).

    Проверяется каждое слово и каждая часть через дефис
    («Кулибин-Незнакомец», «Мудрый незнакомец»): достаточно одной, чтобы
    метка читалась как отдельный безымянный человек. См.
    ``STRANGER_EPITHET_STEMS`` и ``STRANGER_EPITHET_EXCEPTIONS``.
    """
    parts = re.split(r"[\s-]+", normalize_epithet(label))
    return any(
        part.startswith(STRANGER_EPITHET_STEMS)
        and not part.startswith(STRANGER_EPITHET_EXCEPTIONS)
        for part in parts
        if part
    )


# ── Пересмотр ────────────────────────────────────────────────────────────────


def should_review(
    last_review_ts: Optional[float],
    now_ts: float,
    *,
    min_interval_days: int = MIN_REVIEW_INTERVAL_DAYS,
) -> bool:
    """Прошло ли достаточно времени с прошлого пересмотра эпитета.

    ``None`` (никогда не пересматривали) → ``True``.
    """
    if last_review_ts is None:
        return True
    return (now_ts - float(last_review_ts)) >= min_interval_days * SECONDS_PER_DAY


def find_distinctive_topic(
    current_tags: Sequence[str],
    new_tags: Sequence[TagScore],
    *,
    min_share: float = DOMINANT_SHARE,
) -> Optional[str]:
    """Найти НОВУЮ доминирующую тему — повод пересмотреть кличку.

    «Доминирующая» = доля >= ``min_share`` (research §4.1: >40%).
    «Новая» = такого кластера ещё нет в ``current_tags`` профиля. Если
    спикер просто продолжает говорить о том же — возвращаем ``None``, и
    эпитет не трогаем (стабильность важнее реактивности, research §4.6).
    """
    known = {str(t).strip().lower() for t in current_tags if t}
    for tag in new_tags or ():
        if tag.share >= min_share and tag.cluster.lower() not in known:
            return tag.cluster
    return None


