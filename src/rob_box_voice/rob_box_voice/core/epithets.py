# Issue #2926 — живой прогон (акт 2, run 35933157262): LLM вернула «Пока
# нечего показать» вместо клички — это отказ модели («сказать пока нечего»),
# а не 2–4-словная метка, и он прошёл фильтры #2886/#2887, потому что ни
# одно из его слов не входило в проверки, рассчитанные на «Не могу
# придумать». Сюда же «нет данных», «недостаточно информации»,
# «затрудняюсь ответить» — типовые способы модели сказать «фактов нет».
# Сравнение — **по целому слову**, не по префиксу (в отличие от
# ``STRANGER_EPITHET_STEMS``): префикс «пока» поймал бы «Показать»/
# «Показушник», а «ничего» — «Ничейный» (реальный шахматный термин про
# ничью, мог бы стать кличкой). Целым словом эти пересечения не
# срабатывают: «показать» ≠ «пока», «ничейный» ≠ «ничего».
REFUSAL_EPITHET_WORDS: frozenset = frozenset((
    "пока", "нечего", "ничего", "недостаточно", "затрудняюсь",
    "невозможно", "неясно", "непонятно", "неизвестно",
))


def is_refusal_epithet(label: Optional[str]) -> bool:
    """Кличка на деле — отказ/служебный ответ модели, а не метка (issue #2926).

    Сверяется каждое слово целиком (без учёта регистра, ё→е); хватает
    одного совпадения — реплика-отказ обычно и состоит из таких слов
    («Пока нечего показать», «Недостаточно данных для клички»).
    """
    parts = re.split(r"[\s-]+", normalize_epithet(label))
    return any(part in REFUSAL_EPITHET_WORDS for part in parts if part)


