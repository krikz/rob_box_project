def _keys(prefix: str, *statuses: str, **renamed: str) -> Mapping[str, str]:
    keys = {s: f"{prefix}.{s}" for s in statuses}
    keys.update({s: f"{prefix}.{name}" for s, name in renamed.items()})
    return MappingProxyType(keys)


