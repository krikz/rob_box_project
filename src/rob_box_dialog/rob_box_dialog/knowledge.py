# Путь пения (#4079, ADR-0158 §2.2; ADR-0148 п.2 — выбор сужает структура): решает код ДО основной модели
# ---------------------------------------------------------------------------------------------------------------
# Решение — id кандидата (``live:song``, ``live:rap``, ``generate:robot_song:V6``) от хоста хода: его строит
# ``rob_box_music.source.choose_sing`` (маркеры слов, чойсер с перевесом живому). Пакет диалога от ``rob_box_music`` не
# зависит (образы telegram_bot и led_matrix), поэтому решение приходит строкой, а здесь — только что форма хода
# закрывает по каждому пути. Нет решения (не пение, хост без пути пения — чат, оператор) — форма не меняется.

#: Виды выступления, которые робот поёт (``live:<вид>``).
SING_PERFORM_KINDS: Tuple[str, ...] = ("song", "rap")


@dataclass(frozen=True)
class SingForm:
    """Что форма хода делает по пути пения: ``closed_tools`` — тулы вне среза и вне команды (новая музыка мимо
    выступления), ``needs_perform`` — команда обязана петь (``perform``), ``needs_tool`` — команда обязана позвать тул,
    ``kinds`` — допустимые ``perform.kind`` (пусто — вид из id пути), ``backings`` — допустимые подложки (пусто — все)."""

    closed_tools: Tuple[str, ...] = ()
    needs_perform: bool = False
    needs_tool: str = ""
    kinds: Tuple[str, ...] = ()
    backings: Tuple[str, ...] = ()


#: ``live`` — робот поёт сам: ``perform`` вида из id под синт-подложку (``none`` закрыт), генерация и трек закрыты (бит
#: ставит код выступления: ``request_music(intent=backing)`` мимо среза). ``live_over`` — то же, когда музыка уже
#: играет («под этот бит зачитай рэп», акт 8 n810): играющее и есть подложка — ``backing`` только ``none``, выступление
#: идёт поверх, без вопроса «выключить и зачитать?» (``perform.ask_replace_music``) и без второго бита. ``generate``
#: (генерация и кэш) — песню делает ``generate_music`` (фразу о старте строит код по исходу тула), петь выступлением
#: (song/rap) нельзя.
SING_FORMS: Mapping[str, SingForm] = MappingProxyType({
    "live": SingForm(closed_tools=("generate_music", "request_music"), needs_perform=True,
                     backings=tuple(b for b in PERFORM_BACKINGS if b != "none")),
    "live_over": SingForm(closed_tools=("generate_music", "request_music"), needs_perform=True, backings=("none",)),
    "generate": SingForm(needs_tool="generate_music",
                         kinds=tuple(k for k in PERFORM_KINDS if k not in SING_PERFORM_KINDS)),
    # правка играющего (#4029): заказ нового закрыт, правка обязательна; выступление форма не трогает (любой вид)
    "edit": SingForm(closed_tools=("generate_music", "request_music", "dj_set"), needs_tool=EDIT_TOOL,
                     kinds=PERFORM_KINDS),
})
#: Голова id пути хода «правка играющего» (``edit:<вид>+…``, #4029): музыка играет, а реплика её правит («сделай бит
#: потяжелее», «ускорь», «добавь баса»; кейс Шифу 27.10 посреди рэпа, марафон n504–n506). Решает хост до модели тем же
#: вызовом, что путь пения (``rob_box_music.track_edit.edit_route``: слова правки ``TRACK_EDITS`` и снимок плеера), и
#: форма хода сужает выбор структурой (ADR-0148 п.2): ``request_music``/``dj_set``/``generate_music`` вне среза и вне
#: команды, ``edit_music`` обязателен - правка на такте играющего, а не новый трек, платная генерация и мост.
EDIT_ROUTE = "edit"
#: Нарушение формы пути пения: подробность — что именно, допустимое — из :class:`SingForm`.
VIOLATION_SING_ROUTE = "sing_route"


def sing_family(route: str, over_music: bool = False) -> str:
    """Путь пения по id кандидата: ``live:*`` — ``live`` (музыка уже играет, ``over_music`` — ``live_over``); правка
    играющего ``edit:*`` (:data:`EDIT_ROUTE`) — ``edit``; иной непустой (``generate:*``, ``cache:*``) — ``generate``;
    «» — не пение."""
    head = (route or "").split(":", 1)[0]
    if head == EDIT_ROUTE:
        return "edit"
    if head == "live":
        return "live_over" if over_music else "live"
    return "generate" if head else ""


def sing_kinds(route: str) -> Tuple[str, ...]:
    """Допустимые ``perform.kind`` пути пения: ``live:<вид>`` — этот вид (вид вне ``SING_PERFORM_KINDS`` — оба),
    иначе — из :data:`SING_FORMS`; не пение — пусто (как в схеме)."""
    form = SING_FORMS.get(sing_family(route))
    if form is None:
        return ()
    kind = route.split(":")[1] if route.count(":") >= 1 else ""
    if form.kinds:
        return form.kinds
    return (kind,) if kind in SING_PERFORM_KINDS else SING_PERFORM_KINDS


def with_sing(schema: Mapping[str, Any], route: str, over_music: bool = False) -> Dict[str, Any]:
    """Схема команды в форме пути пения: ``perform.kind`` и ``perform.backing`` — перечни пути, ``perform`` обязателен
    на живом пении (ADR-0148 п.2: выбор сужает структура, а не правило в промпте). Подложку вне перечня пути на живом
    пении валидатор ставит первой из перечня — синт (или поверх играющего, ``over_music``) решает код
    (``command._fit_sing_backing``). Путь, где можно только петь (песня, рэп), — без полей ролей ``ROLE_FIELDS``: всё
    звучит голосом робота (#4084). Не пение — без изменений."""
    form = SING_FORMS.get(sing_family(route, over_music))
    out = copy.deepcopy(dict(schema))
    perform = out.get("properties", {}).get("perform")
    if form is None or perform is None:
        return out
    perform["properties"]["kind"] = _enum(sing_kinds(route))
    if not set(sing_kinds(route)) & set(PERFORM_ROLE_KINDS):  # песня и рэп — голосом робота, ролей нет (#4084)
        for name in ROLE_FIELDS:
            perform["properties"].pop(name, None)
    if form.backings:
        perform["properties"]["backing"] = _enum(form.backings)
    if form.needs_perform:
        out["required"] = sorted({*out.get("required", ()), "perform"})
    return out


def _enum(values: Sequence[str]) -> Dict[str, Any]:
    return {"type": "string", "enum": list(values)}


def _object(props: Mapping[str, Any], required: Sequence[str] = ()) -> Dict[str, Any]:
    return {"type": "object", "properties": dict(props), "required": list(required), "additionalProperties": False}


def face_schema() -> Dict[str, Any]:
    """JSON-схема сцены лица (§5.5.9): одна на ``Command.expression.face`` и ``play_animation(face=...)``."""
    face = {slot: _enum(values) for slot, values in FACE_SCENE_SLOTS.items()}
    face["duration_s"] = {"type": "number", "minimum": 0, "maximum": FACE_SCENE_MAX_S}
    schema = _object(face)
    schema["description"] = FACE_SCENE_HINT
    return schema


def _expression_schema() -> Dict[str, Any]:
    """Схема экспрессии команды. ``duration_s`` - сколько держать лицо команды (эмоцию и сцену ``face``), секунды
    (#4083): модель кладёт его на уровень ``expression`` (марафон 23.10: ``fields_dropped=['expression.duration_s']``,
    8 с превращались в 3 с рефлекса); время приводит к ``[FACE_SHOW_MIN_S, FACE_SCENE_MAX_S]`` код
    (``expression.show_seconds``)."""
    return _object({
        "emotion": _enum(EMOTIONS), "gesture": _enum(GESTURES), "earcon": _enum(EARCONS), "face": face_schema(),
        "duration_s": {"type": "number", "minimum": 0, "maximum": FACE_SCENE_MAX_S},
    })


#: Поля ролей выступления в схеме команды (#4084): модель называет героев и чья реплика в сегменте, голоса — решение кода.
ROLE_FIELDS: Tuple[str, ...] = ("cast", "role_per_segment")


def _role_schema() -> Dict[str, Any]:
    """Роли выступления: ``cast`` — герои с репликами (имя и пол), ``role_per_segment`` — чья реплика в каждом сегменте
    (``""`` — рассказчик). Голоса ролей в схеме нет: его даёт код (:mod:`rob_box_dialog.cast`), у роли он один на всё
    выступление — а ``voice_per_segment`` от модели был «голосом на куплет» (#4084: песня про енота — двумя голосами)."""
    role = _object({"name": {"type": "string", "maxLength": ROLE_NAME_MAX_CHARS}, "gender": _enum(ROLE_GENDERS)},
                   required=("name", "gender"))
    return {
        "cast": {"type": "array", "maxItems": PERFORM_CAST_MAX, "items": role},
        "role_per_segment": {"type": "array", "maxItems": SEGMENTS_MAX,
                             "items": {"type": "string", "maxLength": ROLE_NAME_MAX_CHARS}},
    }


def command_schema(mode: str = "json") -> Dict[str, Any]:
    """JSON-схема команды LLM из таблиц этого модуля: ``json`` — сама схема, ``tool`` — тул ``command``.

    :raises ValueError: незнакомый режим.
    """
    if mode not in COMMAND_MODES:
        raise ValueError(f"command_schema: mode must be one of {COMMAND_MODES}, got {mode!r}")
    expression = _expression_schema()
    schema = _object({
        "speech": {"type": "string", "maxLength": SPEECH_MAX_CHARS},
        "voice": {"type": "string", "maxLength": VOICE_MAX_CHARS},
        "ask": _object({"expects": _enum(ASK_EXPECTS), "text": {"type": "string", "maxLength": SPEECH_MAX_CHARS}},
                       required=("expects", "text")),
        "actions": {"type": "array", "maxItems": ACTIONS_MAX,
                    "items": _object({"tool": {"type": "string"}, "args": {"type": "object"}}, required=("tool",))},
        "perform": _object({
            "kind": _enum(PERFORM_KINDS),
            "segments": {"type": "array", "minItems": SEGMENTS_MIN, "maxItems": SEGMENTS_MAX,
                         "items": {"type": "string", "maxLength": SEGMENT_MAX_CHARS}},
            "backing": _enum(PERFORM_BACKINGS),
            "expression_per_segment": {"type": "array", "maxItems": SEGMENTS_MAX, "items": expression},
            **_role_schema(),
        }, required=("kind", "segments")),
        "when": _enum(WHEN),
        "edit_pending": {"type": "boolean"},
        "expression": expression,
        "passed": _enum(PASSED),
    })
    if mode == "json":
        return schema
    return {"type": "function", "function": {
        "name": COMMAND_TOOL, "description": "Одна команда хода: речь, вопрос, действия, экспрессия.",
        "parameters": schema,
    }}


def with_tool_enum(schema: Mapping[str, Any], offered: Iterable[str]) -> Dict[str, Any]:
    """Схема команды, в которой ``actions[].tool`` — перечень тулов СРЕЗА этого хода (ADR-0148: тул вне среза
    невозможен по структуре, а не по просьбе в промпте). Из ``offered`` берутся тулы команды: известные
    ``TOOL_CLASSES`` и тулы речи (модель по привычке кладёт ``speak_text`` в actions — мост переносит его в
    речь). Пусто — схема без изменений: перечень из ничего отверг бы всё."""
    names = sorted({n for n in offered if n in TOOL_CLASSES or n in SPEECH_CHANNEL_TOOLS})
    out = copy.deepcopy(dict(schema))
    if names:
        out["properties"]["actions"]["items"]["properties"]["tool"] = _enum(names)
    return out


def with_voices(schema: Mapping[str, Any], voices: Iterable[str]) -> Dict[str, Any]:
    """Схема команды, в которой голос реплики ``voice`` - голоса звучащего провайдера TTS (#4021; ADR-0148: голос вне
    каталога невозможен по структуре; ``""`` - текущий голос робота). Каталог один - реестр голосов владельца речи, сюда
    он приходит через ``Busy.voices``. Голосов сегментов выступления в схеме нет: их даёт код по ролям (#4084). Пусто -
    схема без изменений."""
    names = sorted({v for v in voices if v})
    out = copy.deepcopy(dict(schema))
    if names and "voice" in out["properties"]:
        out["properties"]["voice"] = _enum(["", *names])
    return out


def without_fields(schema: Mapping[str, Any], fields: Iterable[str]) -> Dict[str, Any]:
    """Схема команды без полей верхнего уровня ``fields`` - закрытых формой хода (``command.Form``, ``FORM_FIELDS``:
    на адресованную реплику нет ``passed``, без просьбы о голосе нет ``voice``). Модель видит только то, что можно."""
    out = copy.deepcopy(dict(schema))
    for name in fields:
        out["properties"].pop(name, None)
    return out


def _roles_line(perform: Mapping[str, Any]) -> str:
    """Строка промпта о ролях выступления — из тех же таблиц, что схема; схема хода без ролей (живое пение) — только
    «одним голосом робота»."""
    sung = "песня и рэп — одним голосом робота, ролей у них нет"
    if "cast" not in perform:
        return f" Всё выступление — голосом робота ({sung})."
    return (f" Роли — только когда в тексте есть герои с репликами ({', '.join(PERFORM_ROLE_KINDS)}; {sung}): cast —"
            f" герои (name и gender ∈ {{{', '.join(ROLE_GENDERS)}}}, ≤ {PERFORM_CAST_MAX}), role_per_segment — чья"
            " реплика в каждом сегменте (\"\" — рассказчик; сегмент = реплика одного говорящего). Голоса ролям даёт"
            " код: у героя один голос на всё выступление. У сказки cast обязателен (героев нет — [])."
            )


