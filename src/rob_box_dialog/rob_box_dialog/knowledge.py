def prompt_fragment(schema: Optional[Mapping[str, Any]] = None) -> str:
    """Фрагмент системного промпта о форме ответа — из тех же таблиц, что схема (не вручную). ``schema`` — схема
    команды этого хода (форма хода закрыла ``passed``/``voice``, #4021): строки о полях, которых в ней нет, не пишутся —
    промпт не предлагает того, чего нет в схеме. ``None`` — полная схема. Первая строка — о шуме распознавания речи
    (:data:`STT_NOISE_NOTE`, #4017): она не зависит от полей схемы.

    Об итоге действий говорит код по событию исполнителя (§4.1, PR-7): ``speech`` при действиях — нарушение
    (``VIOLATION_SPEECH_WITH_ACTIONS``), ответ по сути рядом с действиями («включи звук и расскажи шутку») —
    ``perform``, он звучит всегда.
    """

    def _set(values: Sequence[str]) -> str:
        return "{" + ", ".join(values) + "}"

    face = "; ".join(f"{slot} ∈ {_set(v)}" for slot, v in FACE_SCENE_SLOTS.items())
    props = (schema or command_schema("json"))["properties"]
    fields = set(props)
    # перечни выступления — из схемы хода (путь пения сужает вид и подложку, ``with_sing``), а не из полной таблицы
    perform = props.get("perform", {}).get("properties", {})
    kinds = tuple(perform.get("kind", {}).get("enum", PERFORM_KINDS))
    backings = tuple(perform.get("backing", {}).get("enum", PERFORM_BACKINGS))
    lines: List[Tuple[str, str]] = [
        ("", STT_NOISE_NOTE),
        ("", "Ответ — одна команда (JSON-объект) с полями:"),
        ("speech", f"- speech: реплика человеку, ≤ {SPEECH_MAX_CHARS} символов. С actions speech не пиши (команда"
                   " невалидна): о результате действий скажет код по событию исполнителя; ответ по сути (шутка, стих) —"
                   f" в perform. Исключение — тихие действия {', '.join(QUIET_WITH_SPEECH_TOOLS)}: speech с ними"
                   " звучит."),
        ("voice", "- voice: голос этой реплики (имя голоса, как у speak_text); голос робота не меняет."),
        ("ask", f"- ask: вопрос с ожиданием ответа, expects ∈ {_set(ASK_EXPECTS)}."),
        ("actions", f"- actions: ≤ {ACTIONS_MAX} вызовов тулов {{tool, args}}; не больше одного на класс"
                    f" {' и '.join(SINGLE_ACTION_CLASSES)}."),
        ("perform", f"- perform: выступление kind ∈ {_set(kinds)}, {SEGMENTS_MIN}–{SEGMENTS_MAX} сегментов"
                    f" по ≤ {SEGMENT_MAX_CHARS} символов, backing ∈ {_set(backings)}; вместо speech (speech при"
                    " нём не пиши, даже с actions). Звучит и при actions: ответ по сути (сказка, стих, анекдот), не"
                    " отчёт о действиях." + _roles_line(perform) + " set_voice меняет голос робота насовсем — только"
                    " когда об этом просят."),
        ("when", f"- when ∈ {_set(WHEN)}: after_current — после текущего (по умолчанию), now — сейчас."),
        ("edit_pending", "- edit_pending: true — правка идущего выступления: в perform.segments только новые куплеты,"
                         " они заменят ещё не начатые (с какого — решает код). Пример — «и про енота» посреди рэпа:"
                         " {\"edit_pending\": true, \"perform\": {\"kind\": \"rap\", \"backing\": \"beat\","
                         " \"segments\": [\"А вот и енот — ночной бандит…\", \"Комар и енот — два ночных бойца…\"]}}."),
        ("expression", f"- expression: emotion ∈ {_set(EMOTIONS)}; gesture ∈ {_set(GESTURES)}; earcon ∈"
                       f" {_set(EARCONS)}; face: {face}; duration_s — сколько секунд держать лицо,"
                       f" {FACE_SHOW_MIN_S:g}–{FACE_SCENE_MAX_S:g}."),
        ("passed", f"- passed ∈ {_set(PASSED)} — честно промолчать."),
    ]
    return "\n".join(text for field, text in lines if not field or field in fields)


# ---------------------------------------------------------------------------------------------------------------
# Загрузка вейк-слов из YAML (прод: /config/wake_words.yaml)
# ---------------------------------------------------------------------------------------------------------------


def _wake_entry(item: Any, risky_enabled: bool) -> str:
    """Строка — вейк; ``{word, risky: true}`` — рискованный вейк (В18), берётся только при ``risky_enabled``."""
    if isinstance(item, str):
        return item.strip()
    if isinstance(item, dict) and isinstance(item.get("word"), str):
        return item["word"].strip() if (risky_enabled or not item.get("risky")) else ""
    return ""


def load_wake_word_namespaces(path: "str | os.PathLike[str] | None") -> Dict[str, List[str]]:
    """Прочитать ``wake_words.yaml`` в ``{namespace: [words]}``, порядок — как в файле.

    Записи ``{word: …, risky: true}`` входят, только если в файле ``risky_enabled: true`` (В18).
    Пустой путь, нет файла, битый YAML, чужая структура — ``{}`` (не падает): вызывающий берёт дефолты кода.
    """
    if not path:
        return {}
    import yaml  # noqa: PLC0415 — лениво: без пути модуль не тянет YAML

    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = yaml.safe_load(fh) or {}
    except (OSError, yaml.YAMLError):
        return {}
    if not isinstance(data, dict):
        return {}
    out: Dict[str, List[str]] = {}
    risky_enabled = data.get("risky_enabled") is True
    for namespace in WAKE_NAMESPACES:
        words = data.get(namespace)
        if isinstance(words, list):
            cleaned = [w for w in (_wake_entry(item, risky_enabled) for item in words) if w]
            if cleaned:
                out[namespace] = cleaned
    return out


def resolve_wake_word_namespaces(
    path: "str | os.PathLike[str] | None",
    personality_fallback: Sequence[str] = DEFAULT_WAKE_WORDS,
    operator_fallback: Sequence[str] = DEFAULT_OPERATOR_WAKE_WORDS,
) -> Tuple[List[str], List[str]]:
    """``(personality, operator)``: из файла, а где namespace нет — из переданных фолбеков (порядок важен)."""
    loaded = load_wake_word_namespaces(path)
    personality = loaded.get("personality") or list(personality_fallback)
    operator = loaded.get("operator") or list(operator_fallback)
    return personality, operator
