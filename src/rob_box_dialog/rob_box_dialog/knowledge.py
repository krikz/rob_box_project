@dataclass(frozen=True)
class StopScopeWords:
    """Охват ясного стопа (#3994, ADR-0148: решает код) — закрытая грамматика хвоста после стоп-слова.

    Хвост делится на части союзами ``joins`` и знаками препинания; часть покрыта, если в ней только объекты
    ``objects``, оговорка ``keep`` (фраза из одного-двух слов) и служебные ``filler``. В части с оговоркой названная
    музыка — то, что ОСТАВИТЬ («а музыку оставь»), без неё — то, что погасить («хватит музыки»). Первая непокрытая
    часть и всё после неё — остаток (новая просьба: «хватит, спой другую»); покрытая часть с оговоркой в остатке тоже
    оставляет музыку («хватит, спой другую, а музыку оставь»: оговорка не теряется из-за слова перед ней)."""

    objects: Mapping[str, StopObject]
