def plan_wait_ceiling_s(eta_s: Optional[float]) -> float:
    """Сколько ждать занятый ресурс при оценке ``eta_s`` (``None`` — неизвестно)."""
    return PLAN_WAIT_MAX_S if eta_s is None else min(PLAN_WAIT_MAX_S, eta_s + PLAN_WAIT_SLACK_S)


