"""Офлайн-стенд замера микса (issue #2977, план P3 из
``docs/analysis/2026-08-30-music-quality-audit.md``).

Зачем
=====
Качество сведения оценивалось только на слух — «перегруз» в issue #2963
нечем было измерить (AGENTS.md/ADR-0018: честный результат требует чисел,
не «вроде звучит нормально»). Этот пакет превращает жалобу в число:

* сколько времени сумма слоёв ДО ``tanh`` превышает 1.0 (мягкое насыщение
  на мастер-шине, см. ``docker/vision/voice_assistant/custom_synthdefs/
  masterfilter.scd``);
* true peak и crest factor на выходе;
* спектральный центроид по ролям (бас/пэд/лид/контрголос/ударные);
* число одновременно звучащих слоёв по секциям формы.

Путь рендера (честно, без robota и без SuperCollider)
=======================================================
На Windows-рабочей машине воркера нет ``scsynth`` (SuperCollider не
устанавливается пакетным менеджером Windows в этом окружении) и робота
трогать нельзя (AGENTS.md). Дано на выбор: docker-образ SuperCollider,
NRT-рендер в CI-контейнере, либо чистая Python-модель мастер-цепочки.
Выбран третий путь — :mod:`tools.music_bench.master_chain` — по трём
причинам:

1. Мастер-цепочка ``masterfilter.scd`` — четыре простых, без состояния
   операции (HPF → LPF → tanh → gain), которые НЕ являются кастомным
   SynthDef с тембром: она одна и та же для любого трека, поэтому
   численно воспроизводима вне scsynth без риска разойтись с реальным
   звуком мастер-шины.
2. Тембры отдельных синтов (``wobblebass``, ``wideblip`` и т.п.) внутри
   scsynth воспроизвести без самого scsynth нельзя байт-в-байт — вместо
   этого слои синтезируются РОЛЕВЫМИ архетипами волн (см.
   :mod:`tools.music_bench.synth`): бас — синус, пэд — сумма мягких
   гармоник, лид/контрголос — наивная (без oversampling) пила/треугольник.
   Наивная пила — намеренный выбор: она даёт ТОТ ЖЕ класс алиасинга, что
   и реальные ``saw``/``varsaw``/``supersawlead`` на 16 kHz (RC5 аудита
   30.08), не притворяясь конкретным синтом конкретного трека.
3. Это НЕ замена офлайн-рендера в scsynth NRT — только первая, дешёвая
   итерация (ADR-0013: инкрементально). Ограничения честно описаны в PR
   и в ``docs/music_bench.md``.

Из чего строятся ноты
======================
:mod:`tools.music_bench.note_extract` берёт готовый
``core.arranger.CompositionSpec`` (тот же объект, что уходит в
``arranger.render()`` для реального Renardo-кода) и напрямую читает его
слои/форму — а не парсит сгенерированный текст (парсинг Renardo-кода
регексами уже один раз чуть не сломал музыкальный валидатор, см. историю
``tools/music.py::_PLAYER_LINE_RE`` в аудите). Для тем из RTTTL-библиотеки
(``core.harmonize.Harmonization``) это особенно точно: бас/пэд/лид/
контрголос там уже абсолютные MIDI + биты, ровно то, что реально играет
Renardo — транспонировать ступени лада не нужно вовсе.

Модуль не меняет ни ``core.arranger``, ни ``masterfilter.scd`` — только
читает их (импорт, не правка) и измеряет.
"""

